function Figure1_Known_Surveillance_Analysis
% Publication-ready redraw of Figure 1 using exact saved results.
% No simulation, fitting, or 1-D confidence-interval calculation is run.

close all;
clc;
diary off;

%% 1. Locations

programFolder = fileparts(mfilename('fullpath'));
projectFolder = fileparts(programFolder);

sourceMat = fullfile( ...
    projectFolder, ...
    'Saved_Analysis_Objects', ...
    'Figure1_Known_Surveillance_Analysis_Results.mat');

sourceCsv = fullfile( ...
    projectFolder, ...
    'Data_and_Numerical_Results', ...
    'Figure1_Known_Surveillance_Parameter_Estimates.csv');

outputRoot = fullfile( ...
    projectFolder, ...
    'outputs', ...
    'Figure1_Known_Surveillance_Analysis');

runStamp = datestr(now,'yyyymmdd_HHMMSS');

outputFolder = fullfile( ...
    outputRoot, ...
    ['Run_' runStamp]);

if ~isfolder(projectFolder)
    error( ...
        'The project folder was not found: %s', ...
        projectFolder);
end

if ~isfile(sourceMat)
    error([ ...
        'The exact saved MAT file was not found:\n%s\n\n' ...
        'Run Figure1_Seth_Final_16Panel once before running this redraw.'], ...
        sourceMat);
end

if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

logFile = fullfile( ...
    outputFolder, ...
    'Figure1_Known_Surveillance_Analysis_Command_Window_Log.txt');

diary(logFile);

fprintf('\n');
fprintf('============================================================\n');
fprintf('STARTING THE COMPATIBLE PUBLICATION-READY FIGURE 1 REDRAW\n');
fprintf('No simulation will be run.\n');
fprintf('No parameter will be re-estimated.\n');
fprintf('No saved confidence interval will be changed.\n');
fprintf('The fragile exportgraphics command is not used.\n\n');
fprintf('ALL OUTPUTS WILL BE SAVED AUTOMATICALLY IN:\n%s\n', ...
    outputFolder);
fprintf('============================================================\n\n');

%% 2. Load and validate the saved analysis

saved = load(sourceMat);

required = { ...
    'results', ...
    'countCell', ...
    'p_grid', ...
    'R_true', ...
    'k_true', ...
    'Jmax', ...
    'bounds'};

for q = 1:numel(required)
    if ~isfield(saved,required{q})
        error( ...
            'The saved MAT file is missing the variable %s.', ...
            required{q});
    end
end

results = saved.results;
countCell = saved.countCell;
p_grid = saved.p_grid(:)';
R_true = saved.R_true;
k_true = saved.k_true;
Jmax = saved.Jmax;
bounds = saved.bounds;
numP = numel(p_grid);

if isfield(saved,'N_observed_clusters')
    N_observed_clusters = saved.N_observed_clusters;
else
    N_observed_clusters = sum(countCell{1,1});
end

if numP ~= 4 || ...
        ~isequal(size(results),[4 4]) || ...
        ~isequal(size(countCell),[4 4])

    error( ...
        'The saved analysis is not the expected 4-by-4 surveillance grid.');
end

fprintf('CHECKING THE EXACT SAVED NUMERICAL RESULTS\n');
fprintf('------------------------------------------------------------\n');

for row = 1:numP
    for col = 1:numP

        rr = results(row,col);

        needed = [ ...
            rr.R_hat, ...
            rr.R_lower, ...
            rr.R_upper, ...
            rr.k_hat, ...
            rr.k_lower];

        if any(~isfinite(needed)) || ...
                rr.R_hat <= 0 || ...
                rr.k_hat <= 0

            error( ...
                ['An estimate or lower confidence limit is invalid ' ...
                'in row %d, column %d.'], ...
                row, ...
                col);
        end

        if rr.R_lower > rr.R_hat || ...
                rr.R_upper < rr.R_hat

            error( ...
                ['The saved R_eff interval does not contain its estimate ' ...
                'in row %d, column %d.'], ...
                row, ...
                col);
        end

        if rr.k_lower > rr.k_hat || ...
                (isfinite(rr.k_upper) && rr.k_upper < rr.k_hat)

            error( ...
                ['The saved k interval does not contain its estimate ' ...
                'in row %d, column %d.'], ...
                row, ...
                col);
        end

        if isempty(countCell{row,col}) || ...
                sum(countCell{row,col}) ~= N_observed_clusters

            error( ...
                'A panel does not contain the expected number of observed clusters.');
        end
    end
end

%% 3. Verify the four p_p = 1 panels

pp1col = find(abs(p_grid-1)<1e-12,1);

if isempty(pp1col)
    error( ...
        'The saved surveillance grid does not contain p_p=1.');
end

reference = results(1,pp1col);

referenceValues = [ ...
    reference.R_hat, ...
    reference.R_lower, ...
    reference.R_upper, ...
    reference.k_hat, ...
    reference.k_lower, ...
    reference.k_upper];

for row = 2:numP

    current = results(row,pp1col);

    currentValues = [ ...
        current.R_hat, ...
        current.R_lower, ...
        current.R_upper, ...
        current.k_hat, ...
        current.k_lower, ...
        current.k_upper];

    finiteMask = ...
        isfinite(referenceValues) & ...
        isfinite(currentValues);

    if any(abs( ...
            referenceValues(finiteMask) - ...
            currentValues(finiteMask)) > 1e-10) || ...
            ~isequal( ...
            isinf(referenceValues), ...
            isinf(currentValues))

        error( ...
            'The four saved p_p=1 results are not identical.');
    end

    if ~isequal( ...
            countCell{1,pp1col}, ...
            countCell{row,pp1col})

        error( ...
            'The four saved p_p=1 count datasets are not identical.');
    end
end

uniqueDatasetCount = ...
    numP*(numP-1)+1;

totalIndependentObservedClusters = ...
    uniqueDatasetCount*N_observed_clusters;

kUpperValues = [results.k_upper];

numberKUpperAboveOne = sum( ...
    isfinite(kUpperValues) & ...
    kUpperValues>1);

numberKUpperInfinite = sum( ...
    isinf(kUpperValues));

fprintf('Saved-result checks passed.\n');
fprintf( ...
    'True R_eff = %.4f; true k = %.4f.\n', ...
    R_true, ...
    k_true);
fprintf( ...
    'Observed clusters per unique setting = %d.\n', ...
    N_observed_clusters);
fprintf( ...
    'Unique independently simulated datasets = %d.\n', ...
    uniqueDatasetCount);
fprintf( ...
    'Total independently simulated observed clusters = %d.\n', ...
    totalIndependentObservedClusters);
fprintf( ...
    'Finite k upper limits exceeding 1 = %d.\n', ...
    numberKUpperAboveOne);
fprintf( ...
    'Infinite k upper limits = %d.\n\n', ...
    numberKUpperInfinite);

%% 4. Cross-check the saved CSV against the saved MAT file

if ~isfile(sourceCsv)
    error( ...
        'The exact saved CSV file was not found: %s', ...
        sourceCsv);
end

csvTable = readtable(sourceCsv);

csvNames = { ...
    'p_p', ...
    'p_a', ...
    'R_hat', ...
    'R_lower_95', ...
    'R_upper_95', ...
    'k_hat', ...
    'k_lower_95', ...
    'k_upper_95'};

if ~all(ismember( ...
        csvNames, ...
        csvTable.Properties.VariableNames)) || ...
        height(csvTable) ~= 16

    error( ...
        'The saved CSV does not have the expected 16 rows and columns.');
end

matRows = NaN(16,8);
counter = 0;

for row = 1:numP
    for col = 1:numP

        counter = counter+1;
        rr = results(row,col);

        matRows(counter,:) = [ ...
            rr.p_p, ...
            rr.p_a, ...
            rr.R_hat, ...
            rr.R_lower, ...
            rr.R_upper, ...
            rr.k_hat, ...
            rr.k_lower, ...
            rr.k_upper];
    end
end

csvRows = [ ...
    csvTable.p_p, ...
    csvTable.p_a, ...
    csvTable.R_hat, ...
    csvTable.R_lower_95, ...
    csvTable.R_upper_95, ...
    csvTable.k_hat, ...
    csvTable.k_lower_95, ...
    csvTable.k_upper_95];

matRows = sortrows(matRows,[1 2]);
csvRows = sortrows(csvRows,[1 2]);

finiteMask = ...
    isfinite(matRows) & ...
    isfinite(csvRows);

if any(abs( ...
        matRows(finiteMask) - ...
        csvRows(finiteMask)) > 1e-9) || ...
        ~isequal( ...
        isinf(matRows), ...
        isinf(csvRows))

    error( ...
        'The saved CSV and MAT numerical results do not agree.');
end

fprintf('CSV-versus-MAT check passed exactly.\n\n');

%% 5. Common linear plotting limits

allR = [ ...
    [results.R_hat], ...
    [results.R_lower], ...
    [results.R_upper], ...
    R_true];

allR = allR(isfinite(allR));

Rrange = max( ...
    max(allR)-min(allR), ...
    0.02);

Rpad = max( ...
    0.025, ...
    0.45*Rrange);

RplotMin = max( ...
    bounds.R(1), ...
    min(allR)-Rpad);

RplotMax = min( ...
    bounds.R(2), ...
    max(allR)+Rpad);

allK = [ ...
    [results.k_hat], ...
    [results.k_lower], ...
    [results.k_upper], ...
    k_true];

allK = allK( ...
    isfinite(allK) & ...
    allK>0);

Krange = max( ...
    max(allK)-min(allK), ...
    0.02);

Kpad = max( ...
    0.015, ...
    0.30*Krange);

kPlotMin = max( ...
    bounds.k(1), ...
    min(allK)-Kpad);

kPlotMax = min( ...
    bounds.k(2), ...
    max(allK)+Kpad);

if numberKUpperInfinite>0

    kPlotMax = min( ...
        bounds.k(2), ...
        max(kPlotMax,2*max(allK)));
end

%% 6. Recompute smooth joint contours

deltaNLL_2D = ...
    2.995732273553991;

contourGridN = 91;

kGrid = linspace( ...
    kPlotMin, ...
    kPlotMax, ...
    contourGridN);

RGrid = linspace( ...
    RplotMin, ...
    RplotMax, ...
    contourGridN);

[Kmesh,Rmesh] = meshgrid( ...
    kGrid, ...
    RGrid);

deltaNLLcell = cell(numP,numP);
jointProjection = NaN(numP,numP,4);
truthDeltaNLL = NaN(numP,numP);
jointContainsTruth = false(numP,numP);

fprintf( ...
    'Recomputing smooth 2-D contours from the saved cluster counts...\n');

for row = 1:numP
    for col = 1:numP

        if col==pp1col && row>1

            deltaNLLcell{row,col} = ...
                deltaNLLcell{1,col};

            jointProjection(row,col,:) = ...
                jointProjection(1,col,:);

            truthDeltaNLL(row,col) = ...
                truthDeltaNLL(1,col);

            jointContainsTruth(row,col) = ...
                jointContainsTruth(1,col);

            continue;
        end

        rr = results(row,col);

        counts = ...
            countCell{row,col}(:)';

        observedSizes = ...
            find(counts>0);

        countsNonzero = ...
            counts(observedSizes);

        Kfull = observation_kernel_fast( ...
            rr.p_p, ...
            rr.p_a, ...
            Jmax, ...
            max(observedSizes));

        Kpositive = ...
            Kfull(:,observedSizes+1);

        nllGrid = likelihood_grid_fast( ...
            Rmesh(:), ...
            Kmesh(:), ...
            countsNonzero, ...
            Kpositive, ...
            rr.p_p, ...
            Jmax, ...
            bounds);

        deltaSurface = reshape( ...
            nllGrid-rr.nll_min, ...
            size(Rmesh));

        deltaNLLcell{row,col} = ...
            deltaSurface;

        inside = ...
            deltaSurface<=deltaNLL_2D;

        if any(inside(:))

            insideK = ...
                Kmesh(inside);

            insideR = ...
                Rmesh(inside);

            jointProjection(row,col,:) = [ ...
                min(insideK), ...
                max(insideK), ...
                min(insideR), ...
                max(insideR)];
        end

        nllTruth = likelihood_grid_fast( ...
            R_true, ...
            k_true, ...
            countsNonzero, ...
            Kpositive, ...
            rr.p_p, ...
            Jmax, ...
            bounds);

        truthDeltaNLL(row,col) = ...
            nllTruth-rr.nll_min;

        jointContainsTruth(row,col) = ...
            truthDeltaNLL(row,col) <= ...
            deltaNLL_2D+1e-8;
    end
end

fprintf( ...
    'Smooth contour calculations completed.\n\n');

%% 7. Check one-dimensional coverage

RcontainsTruth = false(numP,numP);
kContainsTruth = false(numP,numP);

for row = 1:numP
    for col = 1:numP

        rr = results(row,col);

        RcontainsTruth(row,col) = ...
            rr.R_lower <= R_true && ...
            R_true <= rr.R_upper;

        kContainsTruth(row,col) = ...
            rr.k_lower <= k_true && ...
            (isinf(rr.k_upper) || ...
            k_true <= rr.k_upper);
    end
end

fprintf( ...
    'One-dimensional R_eff intervals containing truth = %d of 16.\n', ...
    sum(RcontainsTruth(:)));

fprintf( ...
    'One-dimensional k intervals containing truth = %d of 16.\n', ...
    sum(kContainsTruth(:)));

fprintf( ...
    'Joint two-dimensional regions containing truth = %d of 16.\n\n', ...
    sum(jointContainsTruth(:)));

%% 8. Draw the 16-panel figure

fig = figure( ...
    'Color','w', ...
    'InvertHardcopy','on', ...
    'Units','inches', ...
    'Position',[0.35 0.35 16 10.5], ...
    'Renderer','opengl');

tl = tiledlayout( ...
    fig, ...
    9, ...
    4, ...
    'TileSpacing','compact', ...
    'Padding','compact');

legendAxis = nexttile( ...
    tl, ...
    1, ...
    [1 4]);

hold(legendAxis,'on');
axis(legendAxis,'off');

hContour = plot( ...
    legendAxis, ...
    NaN, ...
    NaN, ...
    'k-', ...
    'LineWidth',2.2);

hMLE = plot( ...
    legendAxis, ...
    NaN, ...
    NaN, ...
    'o', ...
    'Color',[0 0.20 0.90], ...
    'MarkerFaceColor',[0 0.35 1], ...
    'MarkerSize',8.5, ...
    'LineWidth',1.2);

hTrue = plot( ...
    legendAxis, ...
    NaN, ...
    NaN, ...
    'd', ...
    'Color',[0.85 0 0], ...
    'MarkerFaceColor',[1 0.10 0.10], ...
    'MarkerSize',8.5, ...
    'LineWidth',1.2);

hCI = plot( ...
    legendAxis, ...
    NaN, ...
    NaN, ...
    '--', ...
    'Color',[0 0.25 0.95], ...
    'LineWidth',2.0);

title( ...
    legendAxis, ...
    ['Known surveillance: joint likelihood and ' ...
    '1-D profile confidence intervals'], ...
    'FontName','Arial', ...
    'FontSize',19, ...
    'FontWeight','bold');

legend( ...
    legendAxis, ...
    [hContour hMLE hTrue hCI], ...
    { ...
    'Joint 2-D 95% contour', ...
    'Estimated pair (MLE)', ...
    'True pair', ...
    'Separate 1-D 95% profile CIs'}, ...
    'Orientation','horizontal', ...
    'NumColumns',4, ...
    'Location','south', ...
    'FontSize',13.5, ...
    'Box','off');

displayRows = ...
    numP:-1:1;

panelLetters = ...
    char('a'+(0:15));

panelCounter = 0;

xTicks = make_readable_k_ticks( ...
    kPlotMin, ...
    kPlotMax);

yTicks = make_readable_R_ticks( ...
    RplotMin, ...
    RplotMax);

for displayRow = 1:numP

    row = displayRows(displayRow);

    for col = 1:numP

        panelCounter = ...
            panelCounter+1;

        tileNumber = ...
            4+(displayRow-1)*8+col;

        ax = nexttile( ...
            tl, ...
            tileNumber, ...
            [2 1]);

        hold(ax,'on');

        rr = results(row,col);

        contour( ...
            ax, ...
            Kmesh, ...
            Rmesh, ...
            deltaNLLcell{row,col}, ...
            [deltaNLL_2D deltaNLL_2D], ...
            'LineColor','k', ...
            'LineWidth',2.2);

        kLow = max( ...
            rr.k_lower, ...
            kPlotMin);

        if isfinite(rr.k_upper)

            kHigh = min( ...
                rr.k_upper, ...
                kPlotMax);

        else

            kHigh = ...
                kPlotMax;
        end

        plot( ...
            ax, ...
            [kLow kHigh], ...
            [rr.R_hat rr.R_hat], ...
            '--', ...
            'Color',[0 0.25 0.95], ...
            'LineWidth',1.9);

        yCap = ...
            0.017*(RplotMax-RplotMin);

        plot( ...
            ax, ...
            [kLow kLow], ...
            rr.R_hat+[-yCap yCap], ...
            '-', ...
            'Color',[0 0.25 0.95], ...
            'LineWidth',1.9);

        if isfinite(rr.k_upper)

            plot( ...
                ax, ...
                [kHigh kHigh], ...
                rr.R_hat+[-yCap yCap], ...
                '-', ...
                'Color',[0 0.25 0.95], ...
                'LineWidth',1.9);

        else

            plot( ...
                ax, ...
                kPlotMax, ...
                rr.R_hat, ...
                '>', ...
                'Color',[0 0.25 0.95], ...
                'MarkerFaceColor',[0 0.25 0.95], ...
                'MarkerSize',7);
        end

        plot( ...
            ax, ...
            [rr.k_hat rr.k_hat], ...
            [rr.R_lower rr.R_upper], ...
            '--', ...
            'Color',[0 0.25 0.95], ...
            'LineWidth',1.9);

        xCap = ...
            0.012*(kPlotMax-kPlotMin);

        plot( ...
            ax, ...
            rr.k_hat+[-xCap xCap], ...
            [rr.R_lower rr.R_lower], ...
            '-', ...
            'Color',[0 0.25 0.95], ...
            'LineWidth',1.9);

        plot( ...
            ax, ...
            rr.k_hat+[-xCap xCap], ...
            [rr.R_upper rr.R_upper], ...
            '-', ...
            'Color',[0 0.25 0.95], ...
            'LineWidth',1.9);

        plot( ...
            ax, ...
            rr.k_hat, ...
            rr.R_hat, ...
            'o', ...
            'Color',[0 0.15 0.95], ...
            'MarkerFaceColor',[0 0.35 1], ...
            'MarkerSize',8, ...
            'LineWidth',1.2);

        plot( ...
            ax, ...
            k_true, ...
            R_true, ...
            'd', ...
            'Color',[0.85 0 0], ...
            'MarkerFaceColor',[1 0.10 0.10], ...
            'MarkerSize',8, ...
            'LineWidth',1.2);

        set( ...
            ax, ...
            'XScale','linear', ...
            'XLim',[kPlotMin kPlotMax], ...
            'YLim',[RplotMin RplotMax], ...
            'XTick',xTicks, ...
            'YTick',yTicks, ...
            'Box','on', ...
            'XGrid','on', ...
            'YGrid','on', ...
            'GridColor',[0.75 0.75 0.75], ...
            'GridAlpha',0.28, ...
            'FontName','Arial', ...
            'FontSize',12.5, ...
            'LineWidth',1.0, ...
            'Layer','top');

        title( ...
            ax, ...
            sprintf( ...
            '(%c) p_p = %.2f, p_a = %.2f', ...
            panelLetters(panelCounter), ...
            rr.p_p, ...
            rr.p_a), ...
            'FontName','Arial', ...
            'FontSize',13.5, ...
            'FontWeight','bold');

        if displayRow<numP
            ax.XTickLabel = [];
        else
            ax.XTickLabel = compose( ...
                '%.3g', ...
                xTicks);
        end

        if col>1
            ax.YTickLabel = [];
        else
            ax.YTickLabel = compose( ...
                '%.2f', ...
                yTicks);
        end
    end
end

xlabel( ...
    tl, ...
    'Dispersion parameter, k', ...
    'FontName','Arial', ...
    'FontSize',18, ...
    'FontWeight','bold');

ylabel( ...
    tl, ...
    'Effective reproduction number, R_{eff}', ...
    'FontName','Arial', ...
    'FontSize',18, ...
    'FontWeight','bold');

drawnow;

%% 9. Construct the quality-control table

qcRows = NaN(16,20);
counter = 0;

for row = 1:numP
    for col = 1:numP

        counter = counter+1;
        rr = results(row,col);

        joint = squeeze( ...
            jointProjection(row,col,:))';

        qcRows(counter,:) = [ ...
            rr.p_p, ...
            rr.p_a, ...
            rr.R_hat, ...
            rr.R_lower, ...
            rr.R_upper, ...
            rr.k_hat, ...
            rr.k_lower, ...
            rr.k_upper, ...
            double(isfinite(rr.k_upper) && rr.k_upper>1), ...
            double(isinf(rr.k_upper)), ...
            joint, ...
            truthDeltaNLL(row,col), ...
            double(jointContainsTruth(row,col)), ...
            double(RcontainsTruth(row,col)), ...
            double(kContainsTruth(row,col)), ...
            sum(countCell{row,col}), ...
            rr.nll_min];
    end
end

qcTable = array2table( ...
    qcRows, ...
    'VariableNames',{ ...
    'p_p', ...
    'p_a', ...
    'R_hat', ...
    'R_lower_1D95', ...
    'R_upper_1D95', ...
    'k_hat', ...
    'k_lower_1D95', ...
    'k_upper_1D95', ...
    'k_upper_exceeds_1', ...
    'k_upper_is_infinite', ...
    'joint_k_min_grid', ...
    'joint_k_max_grid', ...
    'joint_R_min_grid', ...
    'joint_R_max_grid', ...
    'truth_deltaNLL', ...
    'joint95_contains_truth', ...
    'R_1D95_contains_truth', ...
    'k_1D95_contains_truth', ...
    'ObservedClusters', ...
    'MinimumNLL'});

%% 10. Name and save numerical files

pngFile = fullfile( ...
    outputFolder, ...
    'Figure 1.png');

pdfFile = fullfile( ...
    outputFolder, ...
    'Figure 1.pdf');

figFile = fullfile( ...
    outputFolder, ...
    'Figure 1.fig');

qcCsvFile = fullfile( ...
    outputFolder, ...
    'Figure1_Known_Surveillance_Analysis_quality_control.csv');

exactCsvCopy = fullfile( ...
    outputFolder, ...
    'Figure1_Known_Surveillance_Analysis_exact_saved_results.csv');

plotMatFile = fullfile( ...
    outputFolder, ...
    'Figure1_Known_Surveillance_Analysis_plot_data.mat');

readmeFile = fullfile( ...
    outputFolder, ...
    'README_Figure1.txt');

writetable( ...
    qcTable, ...
    qcCsvFile);

copyfile( ...
    sourceCsv, ...
    exactCsvCopy);

save( ...
    plotMatFile, ...
    'results', ...
    'countCell', ...
    'p_grid', ...
    'R_true', ...
    'k_true', ...
    'N_observed_clusters', ...
    'uniqueDatasetCount', ...
    'totalIndependentObservedClusters', ...
    'deltaNLL_2D', ...
    'kGrid', ...
    'RGrid', ...
    'deltaNLLcell', ...
    'jointProjection', ...
    'truthDeltaNLL', ...
    'jointContainsTruth', ...
    'RcontainsTruth', ...
    'kContainsTruth', ...
    'qcTable');

savefig( ...
    fig, ...
    figFile);

%% 11. Save PNG and PDF without exportgraphics

fprintf( ...
    'Saving the full-size PNG with the print engine...\n');

fprintf( ...
    'Saving the vector PDF with the print engine...\n');

[darkFraction,pngWidth,pngHeight,pdfBytes] = ...
    save_with_print_only( ...
    fig, ...
    pngFile, ...
    pdfFile);

fprintf( ...
    'PNG and PDF export checks passed.\n\n');

%% 12. Copy the code

sourceCodeFile = ...
    [mfilename('fullpath') '.m'];

copiedCodeFile = fullfile( ...
    outputFolder, ...
    [mfilename '.m']);

if isfile(sourceCodeFile)
    copyfile( ...
        sourceCodeFile, ...
        copiedCodeFile);
end

%% 13. Write the README

fid = fopen( ...
    readmeFile, ...
    'w');

if fid<0
    error( ...
        'The README file could not be created.');
end

fprintf(fid, ...
    'PUBLICATION-READY FIGURE 1\r\n\r\n');

