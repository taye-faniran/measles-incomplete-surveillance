function nllValues = likelihood_grid_fast( ...
    Rvalues, ...
    kValues, ...
    counts, ...
    Kpositive, ...
    p_p, ...
    Jmax, ...
    bounds)

Rvalues = Rvalues(:);
kValues = kValues(:);

nllValues = ...
    1e100*ones(numel(Rvalues),1);

valid = ...
    isfinite(Rvalues) & ...
    isfinite(kValues) & ...
    Rvalues>=bounds.R(1) & ...
    Rvalues<=bounds.R(2) & ...
    kValues>=bounds.k(1) & ...
    kValues<=bounds.k(2);

validIndices = ...
    find(valid);

blockSize = 180;

for firstIndex = 1:blockSize:numel(validIndices)

    blockIndices = validIndices( ...
        firstIndex:min( ...
        firstIndex+blockSize-1, ...
        numel(validIndices)));

    Rblock = ...
        Rvalues(blockIndices);

    kblock = ...
        kValues(blockIndices);

    pSblock = true_cluster_pmf_batch( ...
        Rblock, ...
        kblock, ...
        Jmax);

    denominator = positive_detection_probability( ...
        Rblock, ...
        kblock, ...
        p_p);

    probabilities = ...
        (pSblock*Kpositive)./denominator;

    probabilities = ...
        max(probabilities,realmin);

    nllValues(blockIndices) = ...
        -sum( ...
        bsxfun( ...
        @times, ...
        log(probabilities), ...
        counts), ...
        2);
end

end

