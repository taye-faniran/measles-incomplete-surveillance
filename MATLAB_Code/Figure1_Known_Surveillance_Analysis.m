function K = observation_kernel_fast(p_p,p_a,Jmax,Omax)

sAll = ...
    (1:Jmax)';

K = ...
    zeros(Jmax,Omax+1);

qPassive = ...
    1-p_p;

z = ...
    p_p+qPassive*p_a;

a = ...
    qPassive*p_a;

b = ...
    qPassive*(1-p_a);

K(:,1) = ...
    qPassive.^sAll;

if b<1e-15

    maxDiagonal = ...
        min(Jmax,Omax);

    diagonalSizes = ...
        (1:maxDiagonal)';

    diagonalIndex = sub2ind( ...
        size(K), ...
        diagonalSizes, ...
        diagonalSizes+1);

    K(diagonalIndex) = ...
        1-a.^diagonalSizes;

    return;
end

for observedSize = 1:Omax

    trueSize = ...
        (observedSize:Jmax)';

    logChoose = ...
        gammaln(trueSize+1) ...
        -gammaln(observedSize+1) ...
        -gammaln(trueSize-observedSize+1);

    if a==0

        logDifference = ...
            observedSize*log(z);

    else

        logDifference = ...
            observedSize*log(z) ...
            +log1p(-(a/z)^observedSize);
    end

    logValue = ...
        logChoose ...
        +(trueSize-observedSize)*log(b) ...
        +logDifference;

    K(trueSize,observedSize+1) = ...
        exp(logValue);
end

K(~isfinite(K)) = 0;

K = ...
    max(K,0);

end

%% ========================================================================

function probability = positive_detection_probability(R,k,p_p)

qPassive = ...
    1-p_p;

if qPassive<=0

    probability = ...
        ones(size(R));

    return;
end

R = R(:);
k = k(:);

T = ...
    zeros(size(R));

for iteration = 1:500

    Tnew = qPassive.*exp( ...
        -k.*log1p( ...
        (R./k).*(1-T)));

    if max(abs(Tnew-T))<1e-13

        T = Tnew;

        break;
    end

    T = Tnew;
end

probability = ...
    max(1-T,realmin);

end

