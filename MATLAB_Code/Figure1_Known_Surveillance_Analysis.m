function ticks = make_readable_k_ticks(lowerLimit,upperLimit)

rangeValue = ...
    upperLimit-lowerLimit;

roughStep = ...
    rangeValue/5;

powerValue = ...
    10^floor(log10(roughStep));

scaledStep = ...
    roughStep/powerValue;

if scaledStep<=1

    niceScaledStep = 1;

elseif scaledStep<=2

    niceScaledStep = 2;

elseif scaledStep<=2.5

    niceScaledStep = 2.5;

elseif scaledStep<=5

    niceScaledStep = 5;

else

    niceScaledStep = 10;
end

step = ...
    niceScaledStep*powerValue;

firstTick = ...
    ceil(lowerLimit/step)*step;

lastTick = ...
    floor(upperLimit/step)*step;

ticks = ...
    firstTick:step:lastTick;

if numel(ticks)<3

    ticks = ...
        linspace(lowerLimit,upperLimit,4);
end

end

