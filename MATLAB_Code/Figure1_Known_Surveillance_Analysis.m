function pS = true_cluster_pmf_batch(R,k,Jmax)

R = R(:);
k = k(:);
j = 1:Jmax;

logP = ...
    -log(j) ...
    +gammaln((k+1).*j-1) ...
    -gammaln(k.*j) ...
    -gammaln(j) ...
    +(j-1).*log(R./k) ...
    -((k+1).*j-1).*log1p(R./k);

pS = ...
    exp(logP);

pS(~isfinite(pS)) = 0;

end

