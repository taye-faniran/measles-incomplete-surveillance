function Figure2_Fixed_Data_Analysis
% FIGURE2_FIXEDDATA_16PANEL_CORRECT
%
% One fixed observed dataset is generated using:
% R_eff = 0.50, k = 0.15, p_p = 0.25, p_a = 0.50.
%
% The same 5,000 observed clusters are analysed 16 times.
% In each panel, p_p and p_a are fixed.
% Only R_eff and k are estimated.

clc;
close all;

%% 1. Main folder and output folder

programFolder = fileparts(mfilename('fullpath'));
projectRoot = fileparts(programFolder);
baseFolder = fullfile(projectRoot,'outputs');

if ~isfolder(baseFolder)
    mkdir(baseFolder);
end

if ~isfolder(baseFolder)
    error('The main folder was not found:\n%s', baseFolder);
end

outputName = 'Figure2_Fixed_Data_Analysis';

outputFolder = fullfile( ...
    baseFolder, ...
    outputName);

if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

logFile = fullfile( ...
    outputFolder, ...
    [outputName '_Command_Window_Log.txt']);

if isfile(logFile)
    delete(logFile);
end

diary(logFile);

diaryCleanup = ...
    onCleanup(@() safe_diary_off()); %#ok<NASGU>

startTimer = tic;

%% 2. Reproducible scientific settings

rng(20260816, 'twister');

R_true = 0.50;
k_true = 0.15;

p_p_true = 0.25;
p_a_true = 0.50;

N_observed_clusters = 5000;

Jmax = 2500;
Omax = 300;

p_p_grid = [0.25, 0.50, 0.75, 1.00];

p_a_grid = [1.00, 0.75, 0.50, 0.25];

bounds.R = [0.02, 0.98];

bounds.k = [0.002, 5.00];

threshold1D = ...
    0.5 * 3.841458820694124;

threshold2D = ...
    0.5 * 5.991464547107979;

numberContourR = 81;

numberContourK = 81;

cacheVersion = ...
    'fixed-data-16-panel-v2-2026-08-16';

cacheFile = fullfile( ...
    outputFolder, ...
    [outputName '_Analysis_Cache.mat']);

forceRecompute = false;

fprintf('============================================================\n');
fprintf('STARTING CORRECT FIGURE 2: ONE FIXED OBSERVED DATASET\n');

fprintf('True transmission: R_eff = %.4f, k = %.4f\n', ...
    R_true, ...
    k_true);

fprintf('True detection: p_p = %.2f, p_a = %.2f\n', ...
    p_p_true, ...
    p_a_true);

fprintf('Fixed observed dataset: %d observed clusters\n', ...
    N_observed_clusters);

fprintf(['At every panel, p_p and p_a are fixed at ' ...
    'the displayed values.\n']);

fprintf('Only R_eff and k are estimated.\n');

fprintf('No spline interpolation is used for the 2-D contours.\n');

fprintf('\nALL FIGURES AND FILES WILL BE SAVED AUTOMATICALLY IN:\n');
fprintf('%s\n', outputFolder);

fprintf('============================================================\n\n');

%% 3. Load cache or perform calculations

loadedCache = false;

if ~forceRecompute && isfile(cacheFile)

    cacheInfo = load( ...
        cacheFile, ...
        'cacheVersion');

    if isfield(cacheInfo, 'cacheVersion') && ...
            strcmp(cacheInfo.cacheVersion, cacheVersion)

        load(cacheFile);

        loadedCache = true;

        fprintf('A matching saved analysis cache was found.\n');

        fprintf(['The fixed data, estimates, confidence intervals, ' ...
            'and contours were loaded.\n\n']);
    end
end

if ~loadedCache

    %% 3A. Generate one fixed observed dataset

    fprintf('Generating the one fixed observed dataset...\n');

    pS_true = true_cluster_pmf( ...
        R_true, ...
        k_true, ...
        Jmax);

    omittedTrueMass = ...
        max(0, 1 - sum(pS_true));

    Ktrue = observation_kernel_vectorized( ...
        p_p_true, ...
        p_a_true, ...
        Jmax, ...
        0:Omax);

    pO_unconditional = ...
        pS_true * Ktrue;

    probabilityClusterObserved = ...
        sum(pS_true) - pO_unconditional(1);

    pO_positive = ...
        pO_unconditional(2:end) ./ ...
        max(probabilityClusterObserved, realmin);

    omittedObservedPositiveMass = ...
        max(0, 1 - sum(pO_positive));

    pO_for_simulation = ...
        max(pO_positive, 0);

    pO_for_simulation = ...
        pO_for_simulation ./ ...
        sum(pO_for_simulation);

    fixedCountsFull = mnrnd( ...
        N_observed_clusters, ...
        pO_for_simulation);

    lastObservedSize = find( ...
        fixedCountsFull > 0, ...
        1, ...
        'last');

    if isempty(lastObservedSize)

        error('No positive observed clusters were generated.');
    end

    fixedCounts = ...
        fixedCountsFull(1:lastObservedSize);

    observedSizesPresent = ...
        find(fixedCounts > 0);

    observedFrequencies = ...
        fixedCounts(observedSizesPresent);

    expectedTrueClustersFor5000Observed = ...
        N_observed_clusters / ...
        probabilityClusterObserved;

    fprintf('Fixed dataset generated successfully.\n');

    fprintf('Largest observed cluster = %d.\n', ...
        lastObservedSize);

    fprintf(['Probability that a true cluster is observed ' ...
        '= %.6f.\n'], ...
        probabilityClusterObserved);

    fprintf(['Expected true clusters needed to obtain 5000 ' ...
        'observed clusters = %.1f.\n\n'], ...
        expectedTrueClustersFor5000Observed);

    %% 3B. Analyse same data under 16 detection assumptions

    numberRows = numel(p_a_grid);

    numberColumns = numel(p_p_grid);

    numberPanels = ...
        numberRows * numberColumns;

    panelLabel = ...
        cell(numberPanels, 1);

    assumedPP = ...
        zeros(numberPanels, 1);

    assumedPA = ...
        zeros(numberPanels, 1);

    R_hat = ...
        NaN(numberPanels, 1);

    R_lower = ...
        NaN(numberPanels, 1);

    R_upper = ...
        NaN(numberPanels, 1);

    k_hat = ...
        NaN(numberPanels, 1);

    k_lower = ...
        NaN(numberPanels, 1);

    k_upper = ...
        NaN(numberPanels, 1);

    minimumNLL = ...
        NaN(numberPanels, 1);

    R_lower_at_bound = ...
        false(numberPanels, 1);

    R_upper_at_bound = ...
        false(numberPanels, 1);

    k_lower_at_bound = ...
        false(numberPanels, 1);

    k_upper_at_bound = ...
        false(numberPanels, 1);

    KfitCell = ...
        cell(numberPanels, 1);

    reusedPP1Panel = [];

    panel = 0;

    for row = 1:numberRows

        for column = 1:numberColumns

            panel = panel + 1;

            p_p_assumed = ...
                p_p_grid(column);

            p_a_assumed = ...
                p_a_grid(row);

            panelLabel{panel} = ...
                sprintf('(%c)', char(96 + panel));

            assumedPP(panel) = ...
                p_p_assumed;

            assumedPA(panel) = ...
                p_a_assumed;

            if abs(p_p_assumed - 1) < 1e-12 && ...
                    ~isempty(reusedPP1Panel)

                source = ...
                    reusedPP1Panel;

                R_hat(panel) = ...
                    R_hat(source);

                R_lower(panel) = ...
                    R_lower(source);

                R_upper(panel) = ...
                    R_upper(source);

                k_hat(panel) = ...
                    k_hat(source);

                k_lower(panel) = ...
                    k_lower(source);

                k_upper(panel) = ...
                    k_upper(source);

                minimumNLL(panel) = ...
                    minimumNLL(source);

                R_lower_at_bound(panel) = ...
                    R_lower_at_bound(source);

                R_upper_at_bound(panel) = ...
                    R_upper_at_bound(source);

                k_lower_at_bound(panel) = ...
                    k_lower_at_bound(source);

                k_upper_at_bound(panel) = ...
                    k_upper_at_bound(source);

                KfitCell{panel} = ...
                    KfitCell{source};

                fprintf('%s assumed p_p=%.2f, p_a=%.2f: ', ...
                    panelLabel{panel}, ...
                    p_p_assumed, ...
                    p_a_assumed);

                fprintf(['reused identical p_p=1 ' ...
                    'calculation.\n']);

                continue;
            end

            panelTimer = tic;

            KfullAssumed = ...
                observation_kernel_vectorized( ...
                p_p_assumed, ...
                p_a_assumed, ...
                Jmax, ...
                [0, observedSizesPresent]);

            KfitCell{panel} = ...
                KfullAssumed;

            nll = @(R,k) ...
                fixed_detection_nll( ...
                R, ...
                k, ...
                observedFrequencies, ...
                KfullAssumed, ...
                Jmax, ...
                bounds);

            [R_hat(panel), ...
                k_hat(panel), ...
                minimumNLL(panel)] = ...
                fit_R_k_multistart( ...
                nll, ...
                bounds);

            [R_CI, ...
                k_CI, ...
                boundFlags] = ...
                profile_likelihood_CI( ...
                nll, ...
                R_hat(panel), ...
                k_hat(panel), ...
                minimumNLL(panel), ...
                bounds, ...
                threshold1D);

            R_lower(panel) = ...
                R_CI(1);

            R_upper(panel) = ...
                R_CI(2);

            k_lower(panel) = ...
                k_CI(1);

            k_upper(panel) = ...
                k_CI(2);

            R_lower_at_bound(panel) = ...
                boundFlags.RLower;

            R_upper_at_bound(panel) = ...
                boundFlags.RUpper;

            k_lower_at_bound(panel) = ...
                boundFlags.KLower;

            k_upper_at_bound(panel) = ...
                boundFlags.KUpper;

            if abs(p_p_assumed - 1) < 1e-12

                reusedPP1Panel = ...
                    panel;
            end

            fprintf('%s assumed p_p=%.2f, p_a=%.2f: ', ...
                panelLabel{panel}, ...
                p_p_assumed, ...
                p_a_assumed);

            fprintf(['R_eff=%.4f [%s, %s], ' ...
                'k=%.5g [%s, %s], %.2f s\n'], ...
                R_hat(panel), ...
                interval_text( ...
                R_lower(panel), ...
                R_lower_at_bound(panel), ...
                'lower'), ...
                interval_text( ...
                R_upper(panel), ...
                R_upper_at_bound(panel), ...
                'upper'), ...
                k_hat(panel), ...
                interval_text( ...
                k_lower(panel), ...
                k_lower_at_bound(panel), ...
                'lower'), ...
                interval_text( ...
                k_upper(panel), ...
                k_upper_at_bound(panel), ...
                'upper'), ...
                toc(panelTimer));
        end
    end

    %% 3C. Determine linear or logarithmic k-axis

    finitePositiveK = [ ...
        k_true; ...
        k_hat; ...
        k_lower( ...
        isfinite(k_lower) & ...
        k_lower > 0); ...
        k_upper( ...
        isfinite(k_upper) & ...
        k_upper > 0)];

    smallestReportedK = ...
        min(finitePositiveK);

    largestReportedK = ...
        max(finitePositiveK);

    reportedKRangeFactor = ...
        largestReportedK / ...
        smallestReportedK;

    useLogK = ...
        reportedKRangeFactor >= 100 || ...
        any(k_upper_at_bound);

    [commonKLimits, ...
        commonRLimits] = ...
        choose_common_axes( ...
        k_true, ...
        R_true, ...
        k_hat, ...
        k_lower, ...
        k_upper, ...
        R_hat, ...
        R_lower, ...
        R_upper, ...
        bounds, ...
        useLogK);

    if useLogK

        kContourValues = ...
            logspace( ...
            log10(commonKLimits(1)), ...
            log10(commonKLimits(2)), ...
            numberContourK);

    else

        kContourValues = ...
            linspace( ...
            commonKLimits(1), ...
            commonKLimits(2), ...
            numberContourK);
    end

    RContourValues = ...
        linspace( ...
        commonRLimits(1), ...
        commonRLimits(2), ...
        numberContourR);

    %% 3D. Compute direct 2-D likelihood contours

    fprintf('\nComputing direct 2-D likelihood contours...\n');

    fprintf(['There is no nuisance-parameter optimization ' ...
        'and no spline.\n']);

    contourDeltaNLL = ...
        cell(numberPanels, 1);

    contourTouchesBoundary = ...
        false(numberPanels, 1);

    reusedPP1Contour = [];

    for panel = 1:numberPanels

        if abs(assumedPP(panel) - 1) < 1e-12 && ...
                ~isempty(reusedPP1Contour)

            contourDeltaNLL{panel} = ...
                contourDeltaNLL{reusedPP1Contour};

            contourTouchesBoundary(panel) = ...
                contourTouchesBoundary( ...
                reusedPP1Contour);

            continue;
        end

        NLLsurface = ...
            direct_nll_surface( ...
            RContourValues, ...
            kContourValues, ...
            observedFrequencies, ...
            KfitCell{panel}, ...
            Jmax, ...
            bounds);

        contourDeltaNLL{panel} = ...
            NLLsurface - ...
            minimumNLL(panel);

        currentDeltaNLL = ...
            contourDeltaNLL{panel};

        boundaryValues = [ ...
            currentDeltaNLL(1,:), ...
            currentDeltaNLL(end,:), ...
            currentDeltaNLL(:,1)', ...
            currentDeltaNLL(:,end)'];

        contourTouchesBoundary(panel) = ...
            any(boundaryValues <= ...
            threshold2D + 1e-6);

        if abs(assumedPP(panel) - 1) < 1e-12

            reusedPP1Contour = ...
                panel;
        end

        fprintf('Direct contour %d of %d completed.\n', ...
            panel, ...
            numberPanels);
    end

    if any(contourTouchesBoundary)

        warning(['At least one 2-D confidence region reaches ' ...
            'the common plotting boundary.']);

    else

        fprintf(['Contour check passed: no joint 95%% ' ...
            'region touches the axes.\n']);
    end

    %% 3E. Save reusable cache

    save(cacheFile, ...
        'cacheVersion', ...
        'R_true', ...
        'k_true', ...
        'p_p_true', ...
        'p_a_true', ...
        'N_observed_clusters', ...
        'Jmax', ...
        'Omax', ...
        'p_p_grid', ...
        'p_a_grid', ...
        'bounds', ...
        'threshold1D', ...
        'threshold2D', ...
        'fixedCounts', ...
        'observedSizesPresent', ...
        'observedFrequencies', ...
        'lastObservedSize', ...
        'probabilityClusterObserved', ...
        'expectedTrueClustersFor5000Observed', ...
        'omittedTrueMass', ...
        'omittedObservedPositiveMass', ...
        'panelLabel', ...
        'assumedPP', ...
        'assumedPA', ...
        'R_hat', ...
        'R_lower', ...
        'R_upper', ...
        'k_hat', ...
        'k_lower', ...
        'k_upper', ...
        'minimumNLL', ...
        'R_lower_at_bound', ...
        'R_upper_at_bound', ...
        'k_lower_at_bound', ...
        'k_upper_at_bound', ...
        'useLogK', ...
        'smallestReportedK', ...
        'largestReportedK', ...
        'reportedKRangeFactor', ...
        'commonKLimits', ...
        'commonRLimits', ...
        'RContourValues', ...
        'kContourValues', ...
        'contourDeltaNLL', ...
        'contourTouchesBoundary', ...
        '-v7.3');

    fprintf(['The verified calculations were saved ' ...
        'in the reusable cache.\n\n']);
end

%% 4. Quality checks

assert( ...
    sum(fixedCounts) == ...
    N_observed_clusters, ...
    ['The fixed observed counts do not ' ...
    'sum to 5000.']);

truthPanel = find( ...
    abs(assumedPP - p_p_true) < 1e-12 & ...
    abs(assumedPA - p_a_true) < 1e-12, ...
    1);

if isempty(truthPanel)

    error(['The true detection pair is missing ' ...
        'from the 16-panel grid.']);
end

pp1Panels = ...
    find(abs(assumedPP - 1) < 1e-12);

if max(abs( ...
        R_hat(pp1Panels) - ...
        R_hat(pp1Panels(1)))) > 1e-10 || ...
        max(abs( ...
        k_hat(pp1Panels) - ...
        k_hat(pp1Panels(1)))) > 1e-10

    error(['The p_p=1 panels are not ' ...
        'identical.']);
end

finiteKUpperExceeds1 = ...
    isfinite(k_upper) & ...
    k_upper > 1;

%% 5. Save numerical CSV files

resultsTable = table( ...
    panelLabel, ...
    assumedPP, ...
    assumedPA, ...
    R_hat, ...
    R_lower, ...
    R_upper, ...
    R_lower_at_bound, ...
    R_upper_at_bound, ...
    k_hat, ...
    k_lower, ...
    k_upper, ...
    k_lower_at_bound, ...
    k_upper_at_bound, ...
    minimumNLL, ...
    contourTouchesBoundary, ...
    finiteKUpperExceeds1, ...
    'VariableNames', { ...
    'Panel', ...
    'Assumed_p_p', ...
    'Assumed_p_a', ...
    'R_hat', ...
    'R_lower_1D95', ...
    'R_upper_1D95', ...
    'R_lower_reached_parameter_bound', ...
    'R_upper_reached_parameter_bound', ...
    'k_hat', ...
    'k_lower_1D95', ...
    'k_upper_1D95', ...
    'k_lower_reached_parameter_bound', ...
    'k_upper_reached_parameter_bound', ...
    'MinimumNLL', ...
    'Joint95ContourTouchesPlotBoundary', ...
    'Finite_k_upper_exceeds_1'});

resultsCSV = fullfile( ...
    outputFolder, ...
    [outputName '_results.csv']);

writetable( ...
    resultsTable, ...
    resultsCSV);

fixedDataTable = table( ...
    observedSizesPresent(:), ...
    observedFrequencies(:), ...
    'VariableNames', { ...
    'ObservedClusterSize', ...
    'Frequency'});

fixedDataCSV = fullfile( ...
    outputFolder, ...
    [outputName ...
    '_fixed_observed_dataset.csv']);

writetable( ...
    fixedDataTable, ...
    fixedDataCSV);

%% 6. Draw 16-panel figure

fig = figure( ...
    'Color', 'w', ...
    'Name', outputName, ...
    'Units', 'inches', ...
    'Position', [0.4 0.4 16 9.5], ...
    'Renderer', 'painters', ...
    'InvertHardcopy', 'on');

tl = tiledlayout( ...
    fig, ...
    4, ...
    4, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

try

    tl.OuterPosition = ...
        [0.055 0.075 0.93 0.80];

catch

    % Older MATLAB versions may not provide OuterPosition.
end

blue = [0.02 0.32 0.95];

red = [0.95 0.05 0.05];

for panel = 1:numel(panelLabel)

    ax = nexttile(tl, panel);

    hold(ax, 'on');

    [Kgrid, Rgrid] = meshgrid( ...
        kContourValues, ...
        RContourValues);

    contour( ...
        ax, ...
        Kgrid, ...
        Rgrid, ...
        contourDeltaNLL{panel}, ...
        [threshold2D threshold2D], ...
        'k-', ...
        'LineWidth', 2.0);

    draw_CI_cross( ...
        ax, ...
        k_hat(panel), ...
        R_hat(panel), ...
        k_lower(panel), ...
        k_upper(panel), ...
        R_lower(panel), ...
        R_upper(panel), ...
        k_lower_at_bound(panel), ...
        k_upper_at_bound(panel), ...
        R_lower_at_bound(panel), ...
        R_upper_at_bound(panel), ...
        commonKLimits, ...
        commonRLimits, ...
        useLogK, ...
        blue);

    plot( ...
        ax, ...
        k_hat(panel), ...
        R_hat(panel), ...
        'o', ...
        'Color', blue, ...
        'MarkerFaceColor', blue, ...
        'MarkerSize', 6.8, ...
        'LineWidth', 1.0);

    plot( ...
        ax, ...
        k_true, ...
        R_true, ...
        'd', ...
        'Color', red, ...
        'MarkerFaceColor', ...
        [1.00 0.08 0.08], ...
        'MarkerSize', 7.2, ...
        'LineWidth', 1.0);

    xlim(ax, commonKLimits);

    ylim(ax, commonRLimits);

    if useLogK

        set(ax, ...
            'XScale', ...
            'log');
    end

    title( ...
        ax, ...
        sprintf('%s  p_p=%.2f, p_a=%.2f', ...
        panelLabel{panel}, ...
        assumedPP(panel), ...
        assumedPA(panel)), ...
        'FontSize', 10, ...
        'FontWeight', 'bold', ...
        'Interpreter', 'tex');

    box(ax, 'on');

    grid(ax, 'on');

    ax.GridAlpha = 0.12;

    ax.FontSize = 9.5;

    ax.LineWidth = 0.9;

    if mod(panel - 1, 4) ~= 0

        ax.YTickLabel = [];
    end

    if panel <= 12

        ax.XTickLabel = [];
    end

    hold(ax, 'off');
end

xlabel( ...
