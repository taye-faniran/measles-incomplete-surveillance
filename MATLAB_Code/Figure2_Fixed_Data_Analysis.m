function bestValue = ...
    robust_global_minimum_1D( ...
    objective, ...
    lower, ...
    upper, ...
    options)

screen = ...
    linspace(lower, upper, 25);

screenValues = ...
    arrayfun(objective, screen);

bestValue = ...
    min(screenValues);

candidate = ...
    false(size(screen));

candidate(1) = ...
    screenValues(1) <= ...
    screenValues(2);

candidate(end) = ...
    screenValues(end) <= ...
    screenValues(end - 1);

candidate(2:end-1) = ...
    screenValues(2:end-1) <= ...
    screenValues(1:end-2) & ...
    screenValues(2:end-1) <= ...
    screenValues(3:end);

candidateIndices = ...
    find(candidate);

for q = 1:numel(candidateIndices)

    i = ...
        candidateIndices(q);

    leftIndex = ...
        max(1, i - 1);

    rightIndex = ...
        min(numel(screen), i + 1);

    if leftIndex == rightIndex

        continue;
    end

    [~, candidateValue] = ...
        fminbnd( ...
        objective, ...
        screen(leftIndex), ...
        screen(rightIndex), ...
        options);

    bestValue = ...
        min(bestValue, candidateValue);
end

end

