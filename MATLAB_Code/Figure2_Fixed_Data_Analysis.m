function [crossing, reachedBoundary] = ...
    find_profile_crossing( ...
    profileFunction, ...
    estimate, ...
    boundary, ...
    target)

gridValues = ...
    linspace(estimate, boundary, 32);

previousX = ...
    gridValues(1);

previousDifference = ...
    profileFunction(previousX) - target;

bracketFound = false;

for i = 2:numel(gridValues)

    currentX = ...
        gridValues(i);

    currentDifference = ...
        profileFunction(currentX) - target;

    if currentDifference >= 0 && ...
            previousDifference < 0

        lowerBracket = ...
            min(previousX, currentX);

        upperBracket = ...
            max(previousX, currentX);

        bracketFound = true;

        break;
    end

    previousX = ...
        currentX;

    previousDifference = ...
        currentDifference;
end

if ~bracketFound

    crossing = ...
        boundary;

    reachedBoundary = true;

    return;
end

crossing = fzero( ...
    @(x)profileFunction(x) - target, ...
    [lowerBracket upperBracket]);

reachedBoundary = false;

end

