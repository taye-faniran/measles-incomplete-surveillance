function pS = true_cluster_pmf(R, k, Jmax)

j = 1:Jmax;

if R <= 0 || k <= 0

    pS = zeros(1, Jmax);

    pS(1) = 1;

    return;
end

logP = ...
    -log(j) ...
    + gammaln((k + 1) .* j - 1) ...
    - gammaln(k .* j) ...
    - gammaln(j) ...
    + (j - 1) .* log(R ./ k) ...
    - ((k + 1) .* j - 1) .* log1p(R ./ k);

pS = exp(logP);

pS(~isfinite(pS)) = 0;

end

%% =====================================================================
function K = observation_kernel_vectorized( ...
    p_p, ...
    p_a, ...
    Jmax, ...
    observedSizes)

observedSizes = ...
    observedSizes(:)';

K = zeros( ...
    Jmax, ...
    numel(observedSizes));

s = (1:Jmax)';

qPassive = 1 - p_p;

z = p_p + ...
    (1 - p_p) .* p_a;

for q = 1:numel(observedSizes)

    o = observedSizes(q);

    if o == 0

        K(:,q) = ...
            qPassive .^ s;

        continue;
    end

    valid = ...
        s >= o;

    sv = ...
        s(valid);

    first = ...
        binomial_probability_fixed_o( ...
        sv, ...
        o, ...
        z);

    second = ...
        qPassive .^ sv .* ...
        binomial_probability_fixed_o( ...
        sv, ...
        o, ...
        p_a);

    values = ...
        max(first - second, 0);

    K(valid,q) = ...
        values;
end

end

%% =====================================================================
function values = ...
    binomial_probability_fixed_o( ...
    s, ...
    o, ...
    p)

values = ...
    zeros(size(s));

if p <= 0

    if o == 0

        values(:) = 1;
    end

elseif p >= 1

    values(s == o) = 1;

else

    logChoose = ...
        gammaln(s + 1) ...
        - gammaln(o + 1) ...
        - gammaln(s - o + 1);

    values = exp( ...
        logChoose ...
        + o .* log(p) ...
        + (s - o) .* log1p(-p));
end

end

