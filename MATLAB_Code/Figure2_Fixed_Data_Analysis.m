function NLL = direct_nll_surface( ...
    Rvalues, ...
    kValues, ...
    counts, ...
    Kfit, ...
    Jmax, ...
    bounds)

Rcolumn = ...
    Rvalues(:);

j = 1:Jmax;

NLL = NaN( ...
    numel(Rcolumn), ...
    numel(kValues));

for ik = 1:numel(kValues)

    k = ...
        kValues(ik);

    baseByJ = ...
        -log(j) ...
        + gammaln((k + 1) .* j - 1) ...
        - gammaln(k .* j) ...
        - gammaln(j);

    logRoverK = ...
        log(Rcolumn ./ k);

    logOnePlusRoverK = ...
        log1p(Rcolumn ./ k);

    logP = ...
        baseByJ ...
        + logRoverK .* (j - 1) ...
        - logOnePlusRoverK .* ...
        ((k + 1) .* j - 1);

    pSMatrix = ...
        exp(logP);

    pSMatrix( ...
        ~isfinite(pSMatrix)) = 0;

    pSelected = ...
        pSMatrix * Kfit;

    denominator = ...
        max( ...
        sum(pSMatrix, 2) - ...
        pSelected(:,1), ...
        realmin);

    pConditional = ...
        pSelected(:,2:end) ./ ...
        denominator;

    pConditional = ...
        max(pConditional, realmin);

    NLL(:,ik) = ...
        -log(pConditional) * ...
        counts(:);
end

end

