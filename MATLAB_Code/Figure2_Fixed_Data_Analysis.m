function value = fixed_detection_nll( ...
    R, ...
    k, ...
    counts, ...
    Kfit, ...
    Jmax, ...
    bounds)

if ~isfinite(R) || ...
        ~isfinite(k) || ...
        R < bounds.R(1) || ...
        R > bounds.R(2) || ...
        k < bounds.k(1) || ...
        k > bounds.k(2)

    value = 1e100;

    return;
end

pS = true_cluster_pmf( ...
    R, ...
    k, ...
    Jmax);

pSelected = ...
    pS * Kfit;

pO0 = ...
    pSelected(1);

denominator = ...
    max( ...
    sum(pS) - pO0, ...
    realmin);

pConditional = ...
    pSelected(2:end) ./ ...
    denominator;

if any(pConditional <= 0) || ...
        any(~isfinite(pConditional))

    value = 1e100;

    return;
end

value = ...
    -sum(counts .* log(pConditional));

if ~isfinite(value)

    value = 1e100;
end

end

