function contour = direct_joint_rk_contour( ...
    mapTheta, ...
    minObjective, ...
    rCI, ...
    kCI, ...
    counts, ...
    kernel, ...
    prior, ...
    cfg)

target = ...
    minObjective ...
    + 0.5*chi2inv(0.95,2);

scaleR = ...
    max( ...
    0.5*(rCI(2)-rCI(1)), ...
    0.03);

scaleK = ...
    max( ...
    0.5*(kCI(2)-kCI(1)), ...
    0.02);

angles = ...
    linspace( ...
    0, ...
    2*pi, ...
    cfg.contourAngles+1);

angles(end) = [];

contourR = nan(size(angles));
contourK = nan(size(angles));

errors = nan(size(angles));
touches = false(size(angles));

for a = 1:numel(angles)

    directionR = sin(angles(a));
    directionK = cos(angles(a));

    maximumRadius = ...
        maximum_contour_radius( ...
        mapTheta, ...
        scaleR, ...
        scaleK, ...
        directionR, ...
        directionK, ...
        cfg);

    lowRadius = 0;

    highRadius = min(0.5,maximumRadius);

    highDifference = ...
        -0.5*chi2inv(0.95,2);

    while highRadius < maximumRadius

        highDifference = ...
            profiled_rk_difference( ...
            highRadius, ...
            mapTheta, ...
            scaleR, ...
            scaleK, ...
            directionR, ...
            directionK, ...
            target, ...
            counts, ...
            kernel, ...
            prior, ...
            cfg);

        if highDifference>=0
            break;
        end

        lowRadius = highRadius;

        highRadius = ...
            min(maximumRadius,2*highRadius);
    end

    if highRadius==maximumRadius && ...
            highDifference<0

        highDifference = ...
            profiled_rk_difference( ...
            highRadius, ...
            mapTheta, ...
            scaleR, ...
            scaleK, ...
            directionR, ...
            directionK, ...
            target, ...
            counts, ...
            kernel, ...
            prior, ...
            cfg);
    end

    if highDifference<0

        radius = maximumRadius;

        touches(a) = true;

        errors(a) = abs(highDifference);

    else

        lowDifference = ...
            profiled_rk_difference( ...
            lowRadius, ...
            mapTheta, ...
            scaleR, ...
            scaleK, ...
            directionR, ...
            directionK, ...
            target, ...
            counts, ...
            kernel, ...
            prior, ...
            cfg);

        for iteration = 1:cfg.contourBisectionIterations

            middleRadius = ...
                0.5*(lowRadius+highRadius);

            middleDifference = ...
                profiled_rk_difference( ...
                middleRadius, ...
                mapTheta, ...
                scaleR, ...
                scaleK, ...
                directionR, ...
                directionK, ...
                target, ...
                counts, ...
                kernel, ...
                prior, ...
                cfg);

            if middleDifference>=0

                highRadius = middleRadius;
                highDifference = middleDifference;

            else

                lowRadius = middleRadius;
                lowDifference = middleDifference;
            end
        end

        if abs(lowDifference)<abs(highDifference)

            radius = lowRadius;
            errors(a) = abs(lowDifference);

        else

            radius = highRadius;
            errors(a) = abs(highDifference);
        end
    end

    contourR(a) = ...
        mapTheta(1) ...
        + radius*scaleR*directionR;

    contourK(a) = ...
        mapTheta(2) ...
        + radius*scaleK*directionK;
end

contour = struct();

contour.r = [contourR contourR(1)];
contour.k = [contourK contourK(1)];

contour.maxThresholdError = max(errors);
contour.touchesBoundary = any(touches);

end

function maximumRadius = maximum_contour_radius( ...
    mapTheta, ...
    scaleR, ...
    scaleK, ...
    directionR, ...
    directionK, ...
    cfg)

