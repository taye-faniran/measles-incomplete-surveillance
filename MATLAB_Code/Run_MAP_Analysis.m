        cfg.maximumAllowedRhat

    warning( ...
        ['Sensitivity MCMC R-hat exceeded %.2f. ' ...
         'Increase burn-in and saved draws before publication.'], ...
        cfg.maximumAllowedRhat);
end

if qc.minimumAcceptance<0.10 || ...
        qc.maximumAcceptance>0.60

    warning( ...
        ['At least one sensitivity MCMC acceptance rate ' ...
         'was outside 0.10-0.60.']);
end

end

