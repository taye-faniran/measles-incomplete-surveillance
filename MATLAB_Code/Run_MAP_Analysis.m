function fixedData = create_fixed_data(cfg)

fprintf( ...
    'Simulating one fixed set of %d true clusters...\n', ...
    cfg.nTrueClusters);

rng(cfg.randomSeed,'twister');

trueSizes = zeros(cfg.nTrueClusters,1);

for i = 1:cfg.nTrueClusters

    trueSizes(i) = simulate_one_true_cluster( ...
        cfg.trueR, ...
        cfg.trueK, ...
        cfg.maxGenerations, ...
        cfg.maximumSimulatedClusterSize);
end

panelLetters = ...
    arrayfun( ...
    @(x) char('a'+x-1), ...
    1:16, ...
    'UniformOutput',false)';

truePP = zeros(16,1);
truePA = zeros(16,1);

observedSizes = cell(16,1);
observedCounts = cell(16,1);

nObserved = zeros(16,1);

panel = 0;

for row = 1:4

    pa = cfg.truePAValues(row);

    for col = 1:4

        panel = panel + 1;

        pp = cfg.truePPValues(col);

        truePP(panel) = pp;
        truePA(panel) = pa;

        observedSizes{panel} = ...
            observe_true_clusters( ...
            trueSizes, ...
            pp, ...
            pa);

        observedCounts{panel} = ...
            sizes_to_counts( ...
            observedSizes{panel});

        nObserved(panel) = ...
            numel(observedSizes{panel});

        fprintf( ...
            '(%s) p_p=%.2f, p_a=%.2f: %d observed clusters.\n', ...
            panelLetters{panel}, ...
            pp, ...
            pa, ...
            nObserved(panel));
    end
end

fixedData = struct();

fixedData.trueClusterSizes = trueSizes;
fixedData.panelLetters = panelLetters;
fixedData.truePP = truePP;
fixedData.truePA = truePA;
fixedData.observedSizes = observedSizes;
fixedData.observedCounts = observedCounts;
fixedData.nObserved = nObserved;

end

function clusterSize = simulate_one_true_cluster( ...
    R, ...
    k, ...
    maxGenerations, ...
    maxClusterSize)

currentGeneration = 1;
clusterSize = 1;
generation = 1;

while currentGeneration > 0 && ...
        generation < maxGenerations

    gammaRates = ...
        gamrnd(k,R/k,currentGeneration,1);

    offspring = ...
        poissrnd(gammaRates);

    currentGeneration = ...
        sum(offspring);

    clusterSize = ...
        clusterSize + currentGeneration;

    generation = generation + 1;

    if clusterSize > maxClusterSize

        error( ...
            ['A simulated cluster exceeded the safety limit. ' ...
             'Increase maximumSimulatedClusterSize only after ' ...
             'checking the parameters.']);
    end
end

if generation >= maxGenerations && ...
        currentGeneration > 0

    error( ...
        'A simulated cluster reached maxGenerations before extinction.');
end

end

function observedSizes = observe_true_clusters( ...
    trueSizes, ...
    pp, ...
    pa)

n = numel(trueSizes);

temporary = zeros(n,1);

kept = 0;

for i = 1:n

    passiveDetected = ...
        binornd(trueSizes(i),pp);

    if passiveDetected > 0

        activeDetected = ...
            binornd( ...
            trueSizes(i)-passiveDetected, ...
            pa);

        kept = kept + 1;

        temporary(kept) = ...
            passiveDetected + activeDetected;
    end
end

