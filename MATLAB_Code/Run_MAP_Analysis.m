if directionR>0

    limits(1) = ...
        (cfg.upperBounds(1)-mapTheta(1)) ...
        /(scaleR*directionR);

elseif directionR<0

    limits(1) = ...
        (cfg.lowerBounds(1)-mapTheta(1)) ...
        /(scaleR*directionR);
