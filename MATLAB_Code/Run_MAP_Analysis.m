end

function candidates = profile_candidates( ...
    mapValue, ...
    bound, ...
    nPoints, ...
    parameterIndex, ...
    direction)

if parameterIndex==2

    candidates = ...
        exp( ...
        linspace( ...
        log(mapValue), ...
        log(bound), ...
        nPoints));

else

    candidates = ...
        linspace( ...
        mapValue, ...
        bound, ...
        nPoints);
end

if strcmp(direction,'lower')
    candidates = candidates(:)';
else
    candidates = candidates(:)';
end

end

function [crossing,atBound,errorAtCrossing] = ...
    find_profile_crossing( ...
    parameterIndex, ...
    mapTheta, ...
    threshold, ...
    counts, ...
    kernel, ...
    prior, ...
    cfg, ...
    candidates)

previousValue = candidates(1);

previousDifference = ...
    -0.5*chi2inv(0.95,1);

crossing = candidates(end);

atBound = true;

errorAtCrossing = ...
    abs(previousDifference);

for i = 2:numel(candidates)

    currentValue = candidates(i);

    currentObjective = ...
        profile_with_one_fixed( ...
        parameterIndex, ...
        currentValue, ...
        mapTheta, ...
        counts, ...
        kernel, ...
        prior, ...
        cfg);

    currentDifference = ...
        currentObjective-threshold;

    if currentDifference>=0

        left = previousValue;
        right = currentValue;

        leftDifference = previousDifference;
        rightDifference = currentDifference;

        for iteration = 1:cfg.profileBisectionIterations

            if parameterIndex==2
                middle = sqrt(left*right);
            else
                middle = 0.5*(left+right);
            end

            middleObjective = ...
                profile_with_one_fixed( ...
                parameterIndex, ...
                middle, ...
                mapTheta, ...
                counts, ...
                kernel, ...
                prior, ...
                cfg);

            middleDifference = ...
                middleObjective-threshold;

            if sign(middleDifference)==sign(leftDifference)

                left = middle;
                leftDifference = middleDifference;

            else

                right = middle;
                rightDifference = middleDifference;
            end
        end

        if abs(leftDifference)<abs(rightDifference)

            crossing = left;
            errorAtCrossing = abs(leftDifference);

        else

            crossing = right;
            errorAtCrossing = abs(rightDifference);
        end

        atBound = false;

        return;
    end

    previousValue = currentValue;
    previousDifference = currentDifference;
    errorAtCrossing = abs(currentDifference);
end

end

