    limits(2) = ...
        (cfg.upperBounds(2)-mapTheta(2)) ...
        /(scaleK*directionK);

elseif directionK<0

    limits(2) = ...
        (cfg.lowerBounds(2)-mapTheta(2)) ...
        /(scaleK*directionK);
end

maximumRadius = ...
    0.999*min(limits);

end

