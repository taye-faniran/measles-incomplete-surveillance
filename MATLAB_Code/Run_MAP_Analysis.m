function Run_MAP_Analysis
% RUN_MAP_ANALYSIS
% -------------------------------------------------------------------------
% final, checkpointed MAP workflow for manuscript Figures 5-7.
%
% Figure 5: baseline MAP estimates of R_eff and k under 16 generating
%           surveillance settings.
% Figure 6: baseline MAP estimates of p_p and p_a under the same settings.
% Figure 7: prior-location sensitivity when true p_p=true p_a=0.50.
%
% Scientific design
% -----------------
% 1. Simulate ONE fixed set of 10,000 true branching-process clusters.
% 2. Pass those same clusters through 16 surveillance settings.
% 3. At every baseline setting, estimate R_eff, k, p_p, and p_a jointly.
% 4. Use the SAME Beta mean-concentration construction for p_p and p_a.
% 5. Use the fixed p_p=p_a=0.50 dataset for nine prior-mean combinations:
%       p_p prior mean in {0.20,0.50,0.80}
%       p_a prior mean in {0.20,0.50,0.80}
% 6. Use direct optimization for profile-posterior intervals and joint
%    R_eff-k regions. No spline interpolation is used.
% 7. Use four adaptive random-walk Metropolis chains in the sensitivity
%    experiment so Figure 7 can display posterior means and 95% credible
%    intervals, rather than treating a MAP point as a full posterior.
%
% Checkpoint design
% -----------------
% Every completed baseline panel and every completed sensitivity scenario
% is saved immediately. If MATLAB stops, run this same file again. Matching
% checkpoints are loaded and only unfinished work is calculated.
%
% Required MATLAB products
% ------------------------
% Optimization Toolbox and Statistics and Machine Learning Toolbox.
% Parallel Computing Toolbox is optional.
% -------------------------------------------------------------------------

clc;
close all;

cfg = default_configuration();
verify_required_toolboxes();

programFolder = fileparts(mfilename('fullpath'));
repositoryRoot = fileparts(programFolder);
projectRoot = fullfile(repositoryRoot,'outputs');

if ~isfolder(projectRoot)
    mkdir(projectRoot);
end

analysisRoot = fullfile( ...
    projectRoot,'Figure5_7_MAP_methodologicalComplete');

checkpointFolder = fullfile(analysisRoot,'Checkpoints');

if ~exist(analysisRoot,'dir')
    mkdir(analysisRoot);
end

if ~exist(checkpointFolder,'dir')
    mkdir(checkpointFolder);
end

runStamp = datestr(now,'yyyymmdd_HHMMSS');
runFolder = fullfile(analysisRoot,['Run_' runStamp]);

suffixNumber = 1;

while exist(runFolder,'dir')
    runFolder = fullfile( ...
        analysisRoot, ...
        sprintf('Run_%s_%02d',runStamp,suffixNumber));

    suffixNumber = suffixNumber + 1;
end

mkdir(runFolder);

logFile = fullfile( ...
    runFolder, ...
    'Run_MAP_Analysis_Command_Window_Log.txt');

diary(logFile);

cleanupDiary = onCleanup(@() diary('off')); %#ok<NASGU>

fprintf('\n============================================================\n');
fprintf('STARTING THE final MAP WORKFLOW\n');
fprintf('True transmission: R_eff = %.4f, k = %.4f\n', ...
    cfg.trueR,cfg.trueK);

fprintf('One fixed set of true clusters = %d\n', ...
    cfg.nTrueClusters);

fprintf('Baseline prior rule for BOTH p_p and p_a:\n');

fprintf( ...
    '  Beta(mu*phi,(1-mu)*phi), mu=%.2f*truth, phi=%.1f\n', ...
    cfg.baselinePriorMeanScale, ...
    cfg.priorConcentration);

fprintf('Sensitivity truth: p_p = 0.50, p_a = 0.50\n');
fprintf('Sensitivity prior means: 0.20, 0.50, and 0.80\n');

fprintf( ...
    'No favorable-dataset selection and no spline interpolation are used.\n');

fprintf('\nCHECKPOINTS ARE STORED IN:\n%s\n', ...
    checkpointFolder);

fprintf('\nALL OUTPUTS FROM THIS RUN WILL BE SAVED IN:\n%s\n', ...
    runFolder);

fprintf('============================================================\n\n');

copy_running_code(runFolder);

signatures = configuration_signatures(cfg);

%% 1. FIXED SIMULATED DATA

dataCheckpoint = fullfile( ...
    checkpointFolder, ...
    'Fixed_Simulation_Data.mat');

if exist(dataCheckpoint,'file')

    loaded = load(dataCheckpoint);

    if isfield(loaded,'checkpointSignature') && ...
            strcmp(loaded.checkpointSignature,signatures.data)

        fixedData = loaded.fixedData;

        fprintf('Matching fixed-data checkpoint found and loaded.\n');

    else

        fprintf( ...
            'The saved data checkpoint uses a different configuration.\n');

        fprintf('A new fixed dataset will be simulated.\n');

        fixedData = create_fixed_data(cfg);

        checkpointSignature = signatures.data; %#ok<NASGU>

        save( ...
            dataCheckpoint, ...
            'fixedData', ...
            'checkpointSignature', ...
            'cfg', ...
            '-v7.3');
    end

else

    fixedData = create_fixed_data(cfg);

    checkpointSignature = signatures.data; %#ok<NASGU>

    save( ...
        dataCheckpoint, ...
        'fixedData', ...
        'checkpointSignature', ...
        'cfg', ...
        '-v7.3');
end

write_true_cluster_csv(fixedData,runFolder);
write_observed_count_csv(fixedData,runFolder);

fprintf('Fixed simulation data are ready.\n');

fprintf('Largest true cluster = %d.\n', ...
    max(fixedData.trueClusterSizes));

fprintf( ...
    'Observed clusters range from %d to %d across the 16 settings.\n\n', ...
    min(fixedData.nObserved), ...
    max(fixedData.nObserved));

maybe_start_parallel_pool(cfg);

%% 2. BASELINE MAP ANALYSIS FOR FIGURES 5 AND 6

fprintf('BASELINE ANALYSIS FOR FIGURES 5 AND 6\n');
fprintf('Each completed panel is checkpointed immediately.\n\n');

baseline = repmat(empty_baseline_result(),16,1);

for panelIndex = 1:16

    panelLetter = fixedData.panelLetters{panelIndex};

    panelCheckpoint = fullfile( ...
        checkpointFolder, ...
        sprintf('Baseline_Panel_%s.mat',panelLetter));

    if exist(panelCheckpoint,'file')

        loaded = load(panelCheckpoint);

        if isfield(loaded,'checkpointSignature') && ...
                strcmp(loaded.checkpointSignature,signatures.baseline)

            baseline(panelIndex) = loaded.panelResult;

            fprintf( ...
                '(%s) loaded from checkpoint: true p_p=%.2f, p_a=%.2f.\n', ...
                panelLetter, ...
                fixedData.truePP(panelIndex), ...
                fixedData.truePA(panelIndex));

            continue;
        end
    end

    counts = fixedData.observedCounts{panelIndex};

    prior = make_beta_prior( ...
        clipped_probability( ...
        cfg.baselinePriorMeanScale*fixedData.truePP(panelIndex)), ...
        clipped_probability( ...
        cfg.baselinePriorMeanScale*fixedData.truePA(panelIndex)), ...
        cfg.priorConcentration);

    fprintf( ...
        '(%s) fitting true p_p=%.2f, p_a=%.2f, n_obs=%d ...\n', ...
        panelLetter, ...
        fixedData.truePP(panelIndex), ...
        fixedData.truePA(panelIndex), ...
        sum(counts));

    panelTimer = tic;

    kernel = make_likelihood_kernel(counts,cfg);

    mapFit = fit_map_multistart( ...
        counts, ...
        kernel, ...
        prior, ...
        cfg);

    [rCI,rAtBound,rError] = direct_profile_interval( ...
        1, ...
        mapFit.theta, ...
        mapFit.objective, ...
        counts, ...
        kernel, ...
        prior, ...
        cfg);

    [kCI,kAtBound,kError] = direct_profile_interval( ...
        2, ...
        mapFit.theta, ...
        mapFit.objective, ...
        counts, ...
        kernel, ...
        prior, ...
        cfg);

    contour = direct_joint_rk_contour( ...
        mapFit.theta, ...
        mapFit.objective, ...
        rCI, ...
        kCI, ...
        counts, ...
        kernel, ...
        prior, ...
        cfg);

    tailQC = likelihood_tail_qc( ...
        mapFit.theta, ...
        counts, ...
        kernel, ...
        cfg);

    panelResult = empty_baseline_result();

    panelResult.panel = panelLetter;
    panelResult.truePP = fixedData.truePP(panelIndex);
    panelResult.truePA = fixedData.truePA(panelIndex);
    panelResult.nObserved = sum(counts);
    panelResult.largestObserved = find(counts>0,1,'last');
    panelResult.prior = prior;
    panelResult.mapTheta = mapFit.theta;
    panelResult.minimumObjective = mapFit.objective;
    panelResult.rCI = rCI;
    panelResult.kCI = kCI;
    panelResult.rAtBound = rAtBound;
    panelResult.kAtBound = kAtBound;
    panelResult.profileThresholdError = max(rError,kError);
    panelResult.contourK = contour.k;
    panelResult.contourR = contour.r;
    panelResult.contourThresholdError = contour.maxThresholdError;
    panelResult.contourTouchesBoundary = contour.touchesBoundary;
    panelResult.trueTailMass = tailQC.trueTailMass;
    panelResult.expectedOmittedCount = tailQC.expectedOmittedCount;
    panelResult.elapsedSeconds = toc(panelTimer);

    baseline(panelIndex) = panelResult;

    checkpointSignature = signatures.baseline; %#ok<NASGU>

    save( ...
        panelCheckpoint, ...
        'panelResult', ...
        'checkpointSignature', ...
        'cfg', ...
        '-v7.3');

    fprintf( ...
        ['    MAP R_eff=%.4f [%.4f,%.4f], ' ...
         'k=%.5f [%.5f,%.5f], ' ...
         'p_p=%.4f, p_a=%.4f, %.1f s\n'], ...
        mapFit.theta(1), ...
        rCI(1), ...
        rCI(2), ...
        mapFit.theta(2), ...
        kCI(1), ...
        kCI(2), ...
        mapFit.theta(3), ...
        mapFit.theta(4), ...
        panelResult.elapsedSeconds);
end

baselineQC = check_baseline_results(baseline,cfg);

write_baseline_csvs(baseline,runFolder,cfg);

%% 3. prespecified PRIOR SENSITIVITY FOR FIGURE 7

fprintf('\nPRIOR-LOCATION SENSITIVITY ANALYSIS FOR FIGURE 7\n');

fprintf( ...
    'The same fixed p_p=0.50, p_a=0.50 observed dataset is used nine times.\n');

fprintf( ...
    'Only the prior means change from one sensitivity scenario to another.\n\n');

sensitivityPanel = find( ...
    abs(fixedData.truePP-0.50)<1e-12 & ...
    abs(fixedData.truePA-0.50)<1e-12, ...
    1);

if isempty(sensitivityPanel)
    error('The fixed p_p=0.50, p_a=0.50 panel was not found.');
end

sensitivityCounts = ...
    fixedData.observedCounts{sensitivityPanel};

sensitivityKernel = ...
    make_likelihood_kernel(sensitivityCounts,cfg);

priorMeans = cfg.sensitivityPriorMeans;

sensitivity = ...
    repmat(empty_sensitivity_result(),9,1);

scenarioIndex = 0;

for ppMeanIndex = 1:numel(priorMeans)

    for paMeanIndex = 1:numel(priorMeans)

        scenarioIndex = scenarioIndex + 1;

        ppMean = priorMeans(ppMeanIndex);
        paMean = priorMeans(paMeanIndex);

        scenarioCheckpoint = fullfile( ...
            checkpointFolder, ...
            sprintf( ...
            'Sensitivity_pp_%02d_pa_%02d.mat', ...
            round(100*ppMean), ...
            round(100*paMean)));

        if exist(scenarioCheckpoint,'file')

            loaded = load(scenarioCheckpoint);

            if isfield(loaded,'checkpointSignature') && ...
                    strcmp( ...
                    loaded.checkpointSignature, ...
                    signatures.sensitivity)

                sensitivity(scenarioIndex) = ...
                    loaded.scenarioResult;

                fprintf( ...
                    ['Sensitivity %d/9 loaded: ' ...
                     'prior means p_p=%.2f, p_a=%.2f.\n'], ...
                    scenarioIndex, ...
                    ppMean, ...
                    paMean);

                continue;
            end
        end

        fprintf( ...
            ['Sensitivity %d/9: ' ...
             'prior means p_p=%.2f, p_a=%.2f ...\n'], ...
            scenarioIndex, ...
            ppMean, ...
            paMean);

        scenarioTimer = tic;

        prior = make_beta_prior( ...
            ppMean, ...
            paMean, ...
            cfg.priorConcentration);

        mapFit = fit_map_multistart( ...
            sensitivityCounts, ...
            sensitivityKernel, ...
            prior, ...
            cfg);

        mcmc = run_parallel_mcmc( ...
            mapFit.theta, ...
            sensitivityCounts, ...
            sensitivityKernel, ...
            prior, ...
            cfg, ...
            scenarioIndex);

        scenarioResult = empty_sensitivity_result();

        scenarioResult.scenario = scenarioIndex;
        scenarioResult.nObserved = sum(sensitivityCounts);
        scenarioResult.ppPriorMean = ppMean;
        scenarioResult.paPriorMean = paMean;
        scenarioResult.prior = prior;
        scenarioResult.mapTheta = mapFit.theta;
        scenarioResult.minimumObjective = mapFit.objective;
        scenarioResult.posteriorMean = mean(mcmc.combinedSamples,1);
        scenarioResult.posteriorMedian = median(mcmc.combinedSamples,1);
        scenarioResult.posteriorLower = ...
            prctile(mcmc.combinedSamples,2.5,1);
        scenarioResult.posteriorUpper = ...
            prctile(mcmc.combinedSamples,97.5,1);
        scenarioResult.rhat = mcmc.rhat;
        scenarioResult.acceptance = mcmc.acceptance;
        scenarioResult.samples = mcmc.combinedSamples;
        scenarioResult.elapsedSeconds = toc(scenarioTimer);

        sensitivity(scenarioIndex) = scenarioResult;

        checkpointSignature = signatures.sensitivity; %#ok<NASGU>

        save( ...
            scenarioCheckpoint, ...
            'scenarioResult', ...
            'checkpointSignature', ...
            'cfg', ...
            '-v7.3');

        fprintf( ...
            ['    MAP=(%.4f,%.4f,%.4f,%.4f); ' ...
             'max R-hat=%.3f; ' ...
             'mean acceptance=%.3f; %.1f s\n'], ...
            mapFit.theta(1), ...
            mapFit.theta(2), ...
            mapFit.theta(3), ...
            mapFit.theta(4), ...
            max(mcmc.rhat), ...
            mean(mcmc.acceptance), ...
            scenarioResult.elapsedSeconds);
    end
end

sensitivityQC = check_sensitivity_results( ...
    sensitivity, ...
    cfg);

write_sensitivity_csvs( ...
    sensitivity, ...
    runFolder, ...
    cfg);

%% 4. DRAW AND IMMEDIATELY SAVE EACH FIGURE

fprintf( ...
    '\nAll numerical calculations are checkpointed. Drawing Figures 5, 6, and 7...\n');

figure5 = draw_figure5(baseline,cfg);

save_publication_figure( ...
    figure5, ...
    runFolder, ...
    'Figure 5');

close(figure5);

fprintf('Figure 5 was drawn and saved successfully.\n');

figure6 = draw_figure6(baseline,cfg);

save_publication_figure( ...
    figure6, ...
    runFolder, ...
    'Figure 6');

close(figure6);

fprintf('Figure 6 was drawn and saved successfully.\n');

figure7 = draw_figure7(sensitivity,cfg);

save_publication_figure( ...
    figure7, ...
    runFolder, ...
    'Figure 7');

close(figure7);

fprintf('Figure 7 was drawn and saved successfully.\n');

%% 5. MASTER MAT FILE AND DOCUMENTATION

masterMatFile = fullfile( ...
    runFolder, ...
    'Figure5_7_MAP_methodologicalComplete_All_Results.mat');

save( ...
    masterMatFile, ...
    'cfg', ...
    'signatures', ...
    'fixedData', ...
    'baseline', ...
    'baselineQC', ...
    'sensitivity', ...
    'sensitivityQC', ...
    '-v7.3');

write_readme( ...
    runFolder, ...
    cfg, ...
    baselineQC, ...
    sensitivityQC);

fprintf('\n============================================================\n');
fprintf('DONE: FIGURES 5, 6, AND 7 WERE CREATED.\n');

fprintf( ...
    'Baseline R_eff 1-D intervals containing truth: %d of 16.\n', ...
    baselineQC.rContainsTruth);

fprintf( ...
    'Baseline k 1-D intervals containing truth: %d of 16.\n', ...
    baselineQC.kContainsTruth);

fprintf( ...
    ['Baseline joint R_eff-k regions ' ...
     'containing truth: %d of 16.\n'], ...
    baselineQC.jointContainsTruth);

fprintf( ...
    ['Largest baseline contour threshold error: ' ...
     '%.6g objective units.\n'], ...
    baselineQC.maxContourError);

fprintf( ...
    'Largest expected omitted count: %.6g.\n', ...
    baselineQC.maxExpectedOmittedCount);

fprintf( ...
    'Largest sensitivity R-hat: %.4f.\n', ...
    sensitivityQC.maxRhat);

fprintf( ...
    'Sensitivity MCMC convergence target: R-hat <= %.2f.\n', ...
    cfg.maximumAllowedRhat);

if baselineQC.publicationReady && ...
        sensitivityQC.publicationReady

    fprintf('ALL AUTOMATIC QUALITY CHECKS PASSED.\n');

else

    fprintf( ...
        'IMPORTANT: AT LEAST ONE QUALITY CHECK NEEDS ATTENTION.\n');

    fprintf( ...
        'Read the warnings above before using the figures in the manuscript.\n');
end

fprintf( ...
    '\nALL OUTPUTS FROM THIS RUN WERE SAVED IN:\n%s\n', ...
    runFolder);

fprintf( ...
    '\nFIGURE 5 PDF: %s\n', ...
    fullfile(runFolder,'Figure 5.pdf'));

fprintf( ...
    'FIGURE 5 PNG: %s\n', ...
    fullfile(runFolder,'Figure 5.png'));

fprintf( ...
    'FIGURE 6 PDF: %s\n', ...
    fullfile(runFolder,'Figure 6.pdf'));

fprintf( ...
    'FIGURE 6 PNG: %s\n', ...
    fullfile(runFolder,'Figure 6.png'));

fprintf( ...
    'FIGURE 7 PDF: %s\n', ...
    fullfile(runFolder,'Figure 7.pdf'));

fprintf( ...
    'FIGURE 7 PNG: %s\n', ...
    fullfile(runFolder,'Figure 7.png'));

fprintf( ...
    'MASTER MAT FILE: %s\n', ...
    masterMatFile);

fprintf( ...
    'README: %s\n', ...
    fullfile(runFolder,'README_MAP_Figures_5_7.txt'));

fprintf( ...
    'COMMAND-WINDOW LOG: %s\n', ...
    logFile);

fprintf('============================================================\n');

end

