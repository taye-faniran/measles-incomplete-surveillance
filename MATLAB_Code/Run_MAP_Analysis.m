function kernel = make_likelihood_kernel(counts,cfg)

counts = counts(:);

positiveX = find(counts>0);

Jmax = cfg.trueClusterTruncation;

j = 1:Jmax;
x = positiveX(:);

logCombination = -inf(numel(x),Jmax);

for row = 1:numel(x)

    valid = j >= x(row);

    logCombination(row,valid) = ...
        gammaln(j(valid)+1) ...
        - gammaln(x(row)+1) ...
        - gammaln(j(valid)-x(row)+1);
end

kernel = struct();

kernel.counts = counts;
kernel.positiveX = positiveX;
kernel.positiveCounts = counts(positiveX);
kernel.j = j;
kernel.x = x;
kernel.logCombination = logCombination;

end

function prior = make_beta_prior( ...
    ppMean, ...
    paMean, ...
    concentration)

prior = struct();

prior.ppMean = ppMean;
prior.paMean = paMean;
prior.concentration = concentration;

prior.ppAlpha = ppMean*concentration;
prior.ppBeta = (1-ppMean)*concentration;

prior.paAlpha = paMean*concentration;
prior.paBeta = (1-paMean)*concentration;

prior.ppLower95 = ...
    betainv(0.025,prior.ppAlpha,prior.ppBeta);

prior.ppUpper95 = ...
    betainv(0.975,prior.ppAlpha,prior.ppBeta);

prior.paLower95 = ...
    betainv(0.025,prior.paAlpha,prior.paBeta);

prior.paUpper95 = ...
    betainv(0.975,prior.paAlpha,prior.paBeta);

end

function p = clipped_probability(p)

p = min(0.98,max(0.02,p));

end

function value = negative_log_posterior( ...
    theta, ...
    counts, ...
    kernel, ...
    prior, ...
    cfg)

if any(~isfinite(theta)) || ...
        any(theta<cfg.lowerBounds) || ...
        any(theta>cfg.upperBounds)

    value = 1e100;

    return;
end

probability = ...
    observed_size_probabilities(theta,kernel);

if any(~isfinite(probability)) || ...
        any(probability<=0)

    value = 1e100;

    return;
end

nll = ...
    -sum( ...
    kernel.positiveCounts .* ...
    log(probability));

pp = theta(3);
pa = theta(4);

logPriorPP = ...
    (prior.ppAlpha-1)*log(pp) ...
    + (prior.ppBeta-1)*log(1-pp) ...
    - betaln(prior.ppAlpha,prior.ppBeta);

logPriorPA = ...
    (prior.paAlpha-1)*log(pa) ...
    + (prior.paBeta-1)*log(1-pa) ...
    - betaln(prior.paAlpha,prior.paBeta);

value = ...
    nll ...
    - logPriorPP ...
    - logPriorPA;

if ~isfinite(value) || ...
        ~isreal(value)

    value = 1e100;
end

end

function probability = observed_size_probabilities(theta,kernel)

R = theta(1);
k = theta(2);
pp = theta(3);
pa = theta(4);

j = kernel.j;
x = kernel.x;

pTrue = ...
    true_cluster_pmf_untruncated(R,k,j);

z = pp + (1-pp)*pa;

logFirst = ...
    kernel.logCombination ...
    + x*log(z) ...
    + (j-x)*log(1-z);

logSecond = ...
    kernel.logCombination ...
    + x*log(pa) ...
    + (j-x)*log(1-pa) ...
    + ones(numel(x),1)*(j*log(1-pp));

firstTerm = exp(logFirst);
secondTerm = exp(logSecond);

conditionalMatrix = ...
    firstTerm - secondTerm;

conditionalMatrix( ...
    conditionalMatrix<0 & ...
    conditionalMatrix>-1e-13) = 0;

if any(conditionalMatrix(:)<0)

    probability = nan(numel(x),1);

    return;
end

unconditionalPositive = ...
    conditionalMatrix*pTrue(:);

zeroProbability = ...
    sum( ...
    ((1-pp).^j).*pTrue);

positiveProbability = ...
    1-zeroProbability;

if positiveProbability<=0

    probability = nan(numel(x),1);

else

    % Do not renormalize over x <= the largest observed cluster.
    probability = ...
        unconditionalPositive/positiveProbability;
end

end

function pTrue = true_cluster_pmf_untruncated(R,k,j)

logP = ...
    -log(j) ...
    + gammaln(k*j+j-1) ...
    - gammaln(k*j) ...
    - gammaln(j) ...
    + (j-1)*log(R/k) ...
    - (k*j+j-1)*log(1+R/k);

pTrue = exp(logP);

end

function qc = likelihood_tail_qc( ...
    theta, ...
    counts, ...
    kernel, ...
    cfg)

pTrue = ...
    true_cluster_pmf_untruncated( ...
    theta(1), ...
    theta(2), ...
    kernel.j);

tailMass = ...
    max(0,1-sum(pTrue));

pp = theta(3);

zeroProbability = ...
    sum( ...
    ((1-pp).^kernel.j).*pTrue);

positiveProbability = ...
    max(realmin,1-zeroProbability);

expectedOmitted = ...
    sum(counts)*tailMass/positiveProbability;

qc = struct( ...
    'trueTailMass',tailMass, ...
    'expectedOmittedCount',expectedOmitted);

if expectedOmitted > ...
        cfg.maximumExpectedOmittedCount

    warning( ...
        ['Expected omitted count %.4g exceeds %.4g. ' ...
         'Increase cfg.trueClusterTruncation before publication.'], ...
        expectedOmitted, ...
        cfg.maximumExpectedOmittedCount);
end

end

