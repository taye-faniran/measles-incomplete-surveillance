function qc = check_baseline_results(results,cfg)

rContains = 0;
kContains = 0;
jointContains = 0;

contourErrors = zeros(16,1);
expectedOmitted = zeros(16,1);
touchesBoundary = false(16,1);

for i = 1:16

    rContains = ...
        rContains ...
        + ( ...
        results(i).rCI(1)<=cfg.trueR && ...
        results(i).rCI(2)>=cfg.trueR);

    kContains = ...
        kContains ...
        + ( ...
        results(i).kCI(1)<=cfg.trueK && ...
        results(i).kCI(2)>=cfg.trueK);

    jointContains = ...
        jointContains ...
        + inpolygon( ...
        cfg.trueK, ...
        cfg.trueR, ...
        results(i).contourK, ...
        results(i).contourR);

    contourErrors(i) = ...
        results(i).contourThresholdError;

    expectedOmitted(i) = ...
        results(i).expectedOmittedCount;

    touchesBoundary(i) = ...
        results(i).contourTouchesBoundary;
end

qc = struct();

qc.rContainsTruth = rContains;
qc.kContainsTruth = kContains;
qc.jointContainsTruth = jointContains;

qc.maxContourError = ...
    max(contourErrors);

qc.maxExpectedOmittedCount = ...
    max(expectedOmitted);

qc.contoursTouchingBoundary = ...
    sum(touchesBoundary);

qc.publicationReady = ...
    qc.maxContourError<=cfg.maximumContourThresholdError && ...
    qc.maxExpectedOmittedCount<=cfg.maximumExpectedOmittedCount && ...
    qc.contoursTouchingBoundary==0;

if qc.maxContourError > ...
        cfg.maximumContourThresholdError

    warning( ...
        'A baseline contour missed its threshold tolerance.');
end

if qc.contoursTouchingBoundary>0

    warning( ...
        '%d baseline contour(s) touched a parameter boundary.', ...
        qc.contoursTouchingBoundary);
end

end

function qc = check_sensitivity_results(results,cfg)

allRhat = ...
    vertcat(results.rhat);

allAcceptance = ...
    cell2mat( ...
    arrayfun( ...
    @(x) x.acceptance(:)', ...
    results, ...
    'UniformOutput',false));

