function verify_required_toolboxes()

if isempty(ver('optim'))

    error( ...
        ['Optimization Toolbox is required because ' ...
         'this workflow uses fmincon.']);
end

if isempty(ver('stats'))

    error( ...
        ['Statistics and Machine Learning Toolbox is required because ' ...
         'this workflow uses Beta, Gamma, Poisson, Binomial, ' ...
         'and chi-square functions.']);
end

end

function maybe_start_parallel_pool(cfg)

if ~cfg.useParallel || isempty(ver('parallel'))

    fprintf( ...
        ['Parallel execution is unavailable or disabled; ' ...
         'calculations will run serially.\n\n']);

    return;
end

try

    pool = gcp('nocreate');

    if isempty(pool)
        parpool('local');
    end

    fprintf( ...
        ['Parallel pool is available for multistart fitting ' ...
         'and MCMC chains.\n\n']);

catch err

    fprintf( ...
        'Parallel pool could not be started: %s\n', ...
        err.message);

    fprintf('The workflow will continue serially.\n\n');
end

end

