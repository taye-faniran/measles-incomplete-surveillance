function [savedTheta,acceptanceRate] = ...
    run_one_mcmc_chain( ...
    mapTheta, ...
    counts, ...
    kernel, ...
    prior, ...
    cfg, ...
    seed, ...
    chainNumber)

rng(seed,'twister');

q = theta_to_unbounded(mapTheta,cfg);

q = ...
    q ...
    + 0.03*chainNumber*randn(1,4);

currentLogTarget = ...
    log_target_unbounded( ...
    q, ...
    counts, ...
    kernel, ...
    prior, ...
    cfg);

totalIterations = ...
    cfg.mcmcBurnIn ...
    + cfg.mcmcSavedPerChain*cfg.mcmcThin;

history = zeros(totalIterations,4);

savedTheta = ...
    zeros(cfg.mcmcSavedPerChain,4);

savedIndex = 0;
accepted = 0;

proposalCovariance = ...
    diag([0.10 0.10 0.10 0.10].^2);

proposalCholesky = ...
    chol(proposalCovariance,'lower');

for iteration = 1:totalIterations

    proposal = ...
        q ...
        + (proposalCholesky*randn(4,1))';

    proposalLogTarget = ...
        log_target_unbounded( ...
        proposal, ...
        counts, ...
        kernel, ...
        prior, ...
        cfg);

    if log(rand) < ...
            proposalLogTarget-currentLogTarget

        q = proposal;

        currentLogTarget = proposalLogTarget;

        accepted = accepted + 1;
    end

    history(iteration,:) = q;

    if iteration<=cfg.mcmcBurnIn && ...
            iteration>=cfg.mcmcAdaptStart && ...
            mod(iteration,cfg.mcmcAdaptEvery)==0

        empiricalCovariance = ...
            cov(history(1:iteration,:));

        proposalCovariance = ...
            (2.38^2/4) ...
            * (empiricalCovariance+1e-6*eye(4));

        proposalCholesky = ...
            safe_cholesky(proposalCovariance);
    end

    if iteration>cfg.mcmcBurnIn && ...
            mod( ...
            iteration-cfg.mcmcBurnIn, ...
            cfg.mcmcThin)==0

        savedIndex = savedIndex + 1;

        [theta,~] = ...
            unbounded_to_theta(q,cfg);

        savedTheta(savedIndex,:) = theta;
    end
end

acceptanceRate = ...
    accepted/totalIterations;

end

function L = safe_cholesky(covariance)

jitter = 1e-10;

for attempt = 1:8

    [L,status] = ...
        chol( ...
        covariance+jitter*eye(size(covariance)), ...
        'lower');

    if status==0
        return;
    end

    jitter = jitter*10;
end

L = diag( ...
    sqrt( ...
    max( ...
    diag(covariance), ...
    1e-4)));

end

function logTarget = log_target_unbounded( ...
    q, ...
    counts, ...
    kernel, ...
    prior, ...
    cfg)

[theta,logJacobian] = ...
    unbounded_to_theta(q,cfg);

nlp = negative_log_posterior( ...
    theta, ...
    counts, ...
    kernel, ...
    prior, ...
    cfg);

logTarget = ...
    -nlp + logJacobian;

if ~isfinite(logTarget)
    logTarget = -1e100;
end

end

function q = theta_to_unbounded(theta,cfg)

scaled = ...
    (theta-cfg.lowerBounds) ...
    ./ (cfg.upperBounds-cfg.lowerBounds);

scaled = ...
    min( ...
    1-1e-12, ...
    max(1e-12,scaled));

q = ...
    log(scaled) ...
    - log(1-scaled);

end

function [theta,logJacobian] = ...
    unbounded_to_theta(q,cfg)

scaled = ...
    1./(1+exp(-q));

width = ...
    cfg.upperBounds-cfg.lowerBounds;

theta = ...
    cfg.lowerBounds ...
    + width.*scaled;

logJacobian = ...
    sum( ...
    log(width) ...
    + log(scaled) ...
    + log(1-scaled));

end

function rhat = gelman_rubin_rhat(samples)

[n,d,m] = size(samples);

rhat = nan(1,d);

for parameter = 1:d

    chainMeans = zeros(m,1);
    chainVariances = zeros(m,1);

    for chain = 1:m

        values = ...
            samples(:,parameter,chain);

        chainMeans(chain) = ...
            mean(values);

        chainVariances(chain) = ...
            var(values,0);
    end

    W = mean(chainVariances);

    B = ...
        n*var(chainMeans,0);

    varianceEstimate = ...
        ((n-1)/n)*W ...
        + B/n;

    if W>0

        rhat(parameter) = ...
            sqrt(varianceEstimate/W);

    else

        rhat(parameter) = Inf;
    end
end

end

