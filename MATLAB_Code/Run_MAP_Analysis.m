function [interval,atBound,thresholdError] = ...
    direct_profile_interval( ...
    parameterIndex, ...
    mapTheta, ...
    minObjective, ...
    counts, ...
    kernel, ...
    prior, ...
    cfg)

threshold = ...
    minObjective ...
    + 0.5*chi2inv(0.95,1);

