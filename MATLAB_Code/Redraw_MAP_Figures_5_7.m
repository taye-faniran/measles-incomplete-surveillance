function limits = padded_limits(values,forcePositive)

values = values(isfinite(values));

minimumValue = min(values);
maximumValue = max(values);

dataRange = maximumValue-minimumValue;

if dataRange<=0
    dataRange = max(abs(maximumValue),0.1);
end

limits = [ ...
    minimumValue-0.08*dataRange, ...
    maximumValue+0.08*dataRange];

if forcePositive
    limits(1) = max(0,limits(1));
end

end

