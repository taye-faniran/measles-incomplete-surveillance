%% ========================================================================
% LOAD OR RECONSTRUCT THE SAVED RESULTS
% =========================================================================
function [loaded,sourceDescription,sourceFolder,loadMode] = ...
    load_saved_analysis(analysisRoot)

if ~exist(analysisRoot,'dir')
    error('The analysis folder does not exist: %s',analysisRoot);
end

% First look for a completed master MAT file.
sourceMat = find_newest_master_mat(analysisRoot);

if ~isempty(sourceMat)

    loaded = load(sourceMat);

    requiredVariables = { ...
        'cfg', ...
        'baseline', ...
        'baselineQC', ...
        'sensitivity', ...
        'sensitivityQC'};

    for i = 1:numel(requiredVariables)

        if ~isfield(loaded,requiredVariables{i})
            error('Required variable %s is missing from %s.', ...
                requiredVariables{i},sourceMat);
        end

    end

    sourceDescription = sourceMat;
    sourceFolder = fileparts(sourceMat);
    loadMode = 'completed master MAT file';

    return;
end

% If the master MAT file does not exist, use the checkpoints.
checkpointFolder = fullfile(analysisRoot,'Checkpoints');

if ~exist(checkpointFolder,'dir')
    error(['Neither a completed master MAT file nor the checkpoint ' ...
        'folder was found. Expected checkpoint folder:\n%s'], ...
        checkpointFolder);
end

fprintf(['No completed master MAT file was found.\n' ...
    'Reconstructing the exact results from the saved checkpoints...\n\n']);

[cfg,baseline] = load_baseline_checkpoints(checkpointFolder);

sensitivity = load_sensitivity_checkpoints(checkpointFolder);

baselineQC = rebuild_baseline_qc(baseline,cfg);

sensitivityQC = rebuild_sensitivity_qc(sensitivity,cfg);

loaded = struct();

loaded.cfg = cfg;
loaded.baseline = baseline;
loaded.baselineQC = baselineQC;
loaded.sensitivity = sensitivity;
loaded.sensitivityQC = sensitivityQC;

sourceDescription = checkpointFolder;

sourceFolder = find_newest_csv_folder(analysisRoot);

loadMode = ...
    '16 baseline checkpoints plus 9 sensitivity checkpoints';

end

function sourceMat = find_newest_master_mat(analysisRoot)

runDirectories = dir(fullfile(analysisRoot,'Run_*'));
runDirectories = runDirectories([runDirectories.isdir]);

candidateFiles = {};
candidateTimes = [];

for i = 1:numel(runDirectories)

    candidate = fullfile( ...
        runDirectories(i).folder, ...
        runDirectories(i).name, ...
        'Figure5_7_MAP_methodologicalComplete_All_Results.mat');

    if exist(candidate,'file')

        information = dir(candidate);

        candidateFiles{end+1,1} = candidate; %#ok<AGROW>
        candidateTimes(end+1,1) = information.datenum; %#ok<AGROW>

    end

end

if isempty(candidateFiles)
    sourceMat = '';
    return;
end

[~,newestIndex] = max(candidateTimes);

sourceMat = candidateFiles{newestIndex};

end

function [cfg,baseline] = ...
    load_baseline_checkpoints(checkpointFolder)

panelLetters = arrayfun( ...
    @(x) char('a'+x-1),1:16,'UniformOutput',false);

baseline = [];
cfg = [];

for i = 1:16

    checkpointFile = fullfile( ...
        checkpointFolder, ...
        sprintf('Baseline_Panel_%s.mat',panelLetters{i}));

    if ~exist(checkpointFile,'file')
        error(['Required baseline checkpoint is missing:\n%s\n\n' ...
            'This is the exact file that must be located.'], ...
            checkpointFile);
    end

    saved = load(checkpointFile);

    if ~isfield(saved,'panelResult') || ~isfield(saved,'cfg')
        error('Baseline checkpoint is incomplete: %s', ...
            checkpointFile);
    end

    if i==1

        baseline = repmat(saved.panelResult,16,1);
        cfg = saved.cfg;

    end

    baseline(i) = saved.panelResult;

end

fprintf('All 16 baseline panel checkpoints were loaded.\n');

end

function sensitivity = ...
    load_sensitivity_checkpoints(checkpointFolder)

priorPercent = [20 50 80];

sensitivity = [];
scenarioIndex = 0;

for ppIndex = 1:3

    for paIndex = 1:3

        scenarioIndex = scenarioIndex + 1;

        checkpointFile = fullfile( ...
            checkpointFolder, ...
            sprintf('Sensitivity_pp_%02d_pa_%02d.mat', ...
            priorPercent(ppIndex),priorPercent(paIndex)));

        if ~exist(checkpointFile,'file')
            error(['Required sensitivity checkpoint is missing:\n%s\n\n' ...
                'This is the exact file that must be located.'], ...
                checkpointFile);
        end

        saved = load(checkpointFile);

        if ~isfield(saved,'scenarioResult')
            error('Sensitivity checkpoint is incomplete: %s', ...
                checkpointFile);
        end

        if scenarioIndex==1
            sensitivity = repmat(saved.scenarioResult,9,1);
        end

        sensitivity(scenarioIndex) = saved.scenarioResult;

    end

end

fprintf('All 9 prior-sensitivity checkpoints were loaded.\n\n');

end

%% ========================================================================
% RECONSTRUCT THE QUALITY-CONTROL SUMMARIES
% =========================================================================
function qc = rebuild_baseline_qc(results,cfg)

rContains = 0;
kContains = 0;
jointContains = 0;

contourErrors = zeros(16,1);
expectedOmitted = zeros(16,1);
touchesBoundary = false(16,1);

for i = 1:16

    rContains = rContains + ...
        (results(i).rCI(1)<=cfg.trueR && ...
         results(i).rCI(2)>=cfg.trueR);

    kContains = kContains + ...
        (results(i).kCI(1)<=cfg.trueK && ...
         results(i).kCI(2)>=cfg.trueK);

    jointContains = jointContains + ...
        inpolygon( ...
        cfg.trueK,cfg.trueR, ...
        results(i).contourK, ...
        results(i).contourR);

    contourErrors(i) = ...
        results(i).contourThresholdError;

    expectedOmitted(i) = ...
        results(i).expectedOmittedCount;

    touchesBoundary(i) = ...
        results(i).contourTouchesBoundary;

end

qc = struct();

qc.rContainsTruth = rContains;
qc.kContainsTruth = kContains;
qc.jointContainsTruth = jointContains;

qc.maxContourError = max(contourErrors);

qc.maxExpectedOmittedCount = max(expectedOmitted);

qc.contoursTouchingBoundary = sum(touchesBoundary);

qc.publicationReady = ...
    qc.maxContourError<=cfg.maximumContourThresholdError && ...
    qc.maxExpectedOmittedCount<=cfg.maximumExpectedOmittedCount && ...
    qc.contoursTouchingBoundary==0;

end

function qc = rebuild_sensitivity_qc(results,cfg)

allRhat = vertcat(results.rhat);

allAcceptance = cell2mat( ...
    arrayfun(@(x) x.acceptance(:)', ...
    results,'UniformOutput',false));

qc = struct();

qc.maxRhat = max(allRhat(:));

qc.minimumAcceptance = min(allAcceptance(:));

qc.maximumAcceptance = max(allAcceptance(:));

qc.publicationReady = ...
    qc.maxRhat<=cfg.maximumAllowedRhat && ...
    qc.minimumAcceptance>=0.10 && ...
    qc.maximumAcceptance<=0.60;

end

function sourceFolder = find_newest_csv_folder(analysisRoot)

runDirectories = dir(fullfile(analysisRoot,'Run_*'));
runDirectories = runDirectories([runDirectories.isdir]);

candidateFolders = {};
candidateTimes = [];

for i = 1:numel(runDirectories)

    folder = fullfile( ...
        runDirectories(i).folder, ...
        runDirectories(i).name);

    baselineCSV = fullfile( ...
        folder,'Figure5_6_MAP_baseline_results.csv');

    sensitivityCSV = fullfile( ...
        folder,'Figure7_prior_sensitivity_results.csv');

    if exist(baselineCSV,'file') && ...
            exist(sensitivityCSV,'file')

        baselineInformation = dir(baselineCSV);

        candidateFolders{end+1,1} = folder; %#ok<AGROW>

        candidateTimes(end+1,1) = ...
            baselineInformation.datenum; %#ok<AGROW>

    end

end

if isempty(candidateFolders)

    sourceFolder = '';

else

    [~,newestIndex] = max(candidateTimes);

    sourceFolder = candidateFolders{newestIndex};

end

end

function verify_saved_results( ...
    baseline,sensitivity,baselineQC,sensitivityQC,cfg)

if numel(baseline)~=16
    error('The saved baseline analysis does not contain 16 panels.');
end

if numel(sensitivity)~=9
    error('The saved sensitivity analysis does not contain 9 scenarios.');
end

for i = 1:16

    requiredNumbers = [ ...
        baseline(i).mapTheta(:); ...
        baseline(i).rCI(:); ...
        baseline(i).kCI(:); ...
        baseline(i).contourR(:); ...
        baseline(i).contourK(:)];

    if any(~isfinite(requiredNumbers))
        error(['Baseline panel %d contains a missing ' ...
            'or non-finite number.'],i);
    end

    if numel(baseline(i).contourR) ~= ...
            numel(baseline(i).contourK)

        error(['Baseline panel %d has mismatched ' ...
            'contour coordinates.'],i);

    end

end

for i = 1:9

    requiredNumbers = [ ...
        sensitivity(i).posteriorMean(:); ...
        sensitivity(i).posteriorLower(:); ...
        sensitivity(i).posteriorUpper(:); ...
        sensitivity(i).rhat(:)];

    if any(~isfinite(requiredNumbers))
        error('Sensitivity scenario %d contains a missing number.',i);
    end

end

if baselineQC.maxContourError > ...
        cfg.maximumContourThresholdError

    error('The saved contour error exceeds its required tolerance.');

end

if baselineQC.maxExpectedOmittedCount > ...
        cfg.maximumExpectedOmittedCount

    error(['The saved numerical truncation error ' ...
        'exceeds its tolerance.']);

end

if sensitivityQC.maxRhat > ...
        cfg.maximumAllowedRhat

    error(['The saved sensitivity chains do not pass ' ...
        'the R-hat requirement.']);

end

end

