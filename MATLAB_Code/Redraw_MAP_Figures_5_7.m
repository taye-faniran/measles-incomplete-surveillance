function fig = draw_neat_figure5(results,cfg)

fig = figure( ...
    'Color','w', ...
    'Units','pixels', ...
    'Position',[30 30 2400 1500], ...
    'Renderer','painters', ...
    'Name','Figure 5 - MAP transmission estimates');

fontName = 'Helvetica';

allK = cfg.trueK;
allR = cfg.trueR;

for i = 1:16

    allK = [allK results(i).contourK results(i).kCI]; %#ok<AGROW>
    allR = [allR results(i).contourR results(i).rCI]; %#ok<AGROW>

end

kRange = max(allK)-min(allK);
rRange = max(allR)-min(allR);

if kRange<=0
    kRange = 0.05;
end

if rRange<=0
    rRange = 0.05;
end

kLimits = [ ...
    max(0,min(allK)-0.06*kRange), ...
    max(allK)+0.06*kRange];

rLimits = [ ...
    min(allR)-0.08*rRange, ...
    max(allR)+0.08*rRange];

left = 0.065;
right = 0.985;
bottom = 0.095;
top = 0.815;

horizontalGap = 0.025;
verticalGap = 0.040;

panelWidth = ...
    (right-left-3*horizontalGap)/4;

panelHeight = ...
    (top-bottom-3*verticalGap)/4;

for i = 1:16

    row = ceil(i/4);
    col = mod(i-1,4)+1;

    xPosition = ...
        left+(col-1)*(panelWidth+horizontalGap);

    yPosition = ...
        top-row*panelHeight-(row-1)*verticalGap;

    ax = axes( ...
        'Parent',fig, ...
        'Position', ...
        [xPosition yPosition panelWidth panelHeight]);

    hold(ax,'on');

    % Joint 95% profile-posterior contour.
    plot(ax, ...
        results(i).contourK, ...
        results(i).contourR, ...
        'k-', ...
        'LineWidth',2.0);

    % Separate one-dimensional interval for k.
    plot(ax, ...
        results(i).kCI, ...
        [results(i).mapTheta(1) ...
         results(i).mapTheta(1)], ...
        'b--', ...
        'LineWidth',1.6);

    % Separate one-dimensional interval for R_eff.
    plot(ax, ...
        [results(i).mapTheta(2) ...
         results(i).mapTheta(2)], ...
        results(i).rCI, ...
        'b--', ...
        'LineWidth',1.6);

    % MAP estimate.
    plot(ax, ...
        results(i).mapTheta(2), ...
        results(i).mapTheta(1), ...
        'o', ...
        'MarkerSize',7, ...
        'MarkerFaceColor',[0.05 0.35 0.95], ...
        'MarkerEdgeColor',[0 0.15 0.65]);

    % True transmission pair.
    plot(ax, ...
        cfg.trueK,cfg.trueR, ...
        'd', ...
        'MarkerSize',8, ...
        'MarkerFaceColor',[1 0.12 0.12], ...
        'MarkerEdgeColor',[0.75 0 0]);

    xlim(ax,kLimits);
    ylim(ax,rLimits);

    grid(ax,'on');
    box(ax,'on');

    set(ax, ...
        'FontName',fontName, ...
        'FontSize',9.5, ...
        'LineWidth',0.9, ...
        'Layer','top', ...
        'TickDir','out');

    title(ax, ...
        sprintf('(%s)  p_p=%.2f, p_a=%.2f', ...
        results(i).panel, ...
        results(i).truePP, ...
        results(i).truePA), ...
        'Interpreter','tex', ...
        'FontName',fontName, ...
        'FontWeight','bold', ...
        'FontSize',10.5);

    if col>1
        set(ax,'YTickLabel',[]);
    end

    if row<4
        set(ax,'XTickLabel',[]);
    end

end

add_canvas_text( ...
    fig,[0.05 0.945 0.90 0.04], ...
    'MAP transmission estimates', ...
    20,'bold',0,fontName,'none');

draw_figure5_key(fig,fontName);

add_canvas_text( ...
    fig,[0.35 0.015 0.34 0.04], ...
    'Dispersion parameter, k', ...
    15,'bold',0,fontName,'tex');

add_canvas_text( ...
    fig,[0.004 0.32 0.035 0.38], ...
    'Effective reproduction number, R_{eff}', ...
    15,'bold',90,fontName,'tex');

end

