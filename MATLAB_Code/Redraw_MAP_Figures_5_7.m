function draw_sensitivity_panel( ...
    ax,x,labels, ...
    posteriorMean,posteriorLower,posteriorUpper, ...
    priorMean,priorLower,priorUpper, ...
    truth,yLimits,titleText,yLabelText, ...
    showPrior,showXLabels,fontName)

x = x(:);

posteriorMean = posteriorMean(:);
posteriorLower = posteriorLower(:);
posteriorUpper = posteriorUpper(:);

labels = labels(:);

hold(ax,'on');

% Separate the three groups of p_p prior means.
for boundary = [3.5 6.5]

    plot(ax,[boundary boundary],yLimits, ...
        ':', ...
        'Color',[0.70 0.70 0.70], ...
        'LineWidth',1.0);

end

% True parameter value.
plot(ax, ...
    [0.5 numel(x)+0.5], ...
    [truth truth], ...
    'r-', ...
    'LineWidth',1.8);

% Prior mean and prior 95% interval, shown only for p_p and p_a.
if showPrior

    priorMean = priorMean(:);
    priorLower = priorLower(:);
    priorUpper = priorUpper(:);

    errorbar(ax, ...
        x-0.12, ...
        priorMean, ...
        priorMean-priorLower, ...
        priorUpper-priorMean, ...
        's', ...
        'Color',[0.40 0.40 0.40], ...
        'MarkerFaceColor',[0.72 0.72 0.72], ...
        'MarkerSize',5.5, ...
        'LineWidth',1.3, ...
        'CapSize',6);

end

% Posterior mean and posterior 95% credible interval.
errorbar(ax, ...
    x+0.12*showPrior, ...
    posteriorMean, ...
    posteriorMean-posteriorLower, ...
    posteriorUpper-posteriorMean, ...
    'o', ...
    'Color',[0.05 0.35 0.95], ...
    'MarkerFaceColor',[0.05 0.35 0.95], ...
    'MarkerSize',6, ...
    'LineWidth',1.4, ...
    'CapSize',7);

xlim(ax,[0.5 numel(x)+0.5]);
ylim(ax,yLimits);

grid(ax,'on');
box(ax,'on');

set(ax, ...
    'XTick',x, ...
    'FontName',fontName, ...
    'FontSize',10, ...
    'LineWidth',0.9, ...
    'TickDir','out', ...
    'Layer','top');

if showXLabels

    set(ax, ...
        'XTickLabel',labels, ...
        'XTickLabelRotation',30);

else

    set(ax,'XTickLabel',[]);

end

ylabel(ax,yLabelText, ...
    'Interpreter','tex', ...
    'FontName',fontName, ...
    'FontSize',12, ...
    'FontWeight','bold');

title(ax,titleText, ...
    'Interpreter','tex', ...
    'FontName',fontName, ...
    'FontSize',14, ...
    'FontWeight','bold');

end

